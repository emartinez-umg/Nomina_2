import oracledb from 'oracledb';
import type { Connection } from 'oracledb';
import type { JornadaDia } from './horas.js';
// Fragmento SQL estático compartido: una fila por bloque/día y descansos explícitos.
export const distribucionHorarioSql = `SELECT B.ID_HORARIO,D.DIA_SEMANA,1 LABORABLE,B.MINUTO_ENTRADA,B.MINUTO_SALIDA,B.CRUZA_MEDIANOCHE,B.MINUTOS_DESCANSO,1 ACTIVO FROM HORARIO_BLOQUES B JOIN HORARIO_BLOQUE_DIAS D ON D.ID_HORARIO_BLOQUE=B.ID_HORARIO_BLOQUE WHERE B.ACTIVO=1 AND D.ACTIVO=1
UNION ALL
SELECT H.ID_HORARIO,S.DIA_SEMANA,0,NULL,NULL,0,0,1 FROM HORARIOS H CROSS JOIN (SELECT LEVEL DIA_SEMANA FROM DUAL CONNECT BY LEVEL<=7) S WHERE NOT EXISTS (SELECT 1 FROM HORARIO_BLOQUES B JOIN HORARIO_BLOQUE_DIAS D ON D.ID_HORARIO_BLOQUE=B.ID_HORARIO_BLOQUE WHERE B.ID_HORARIO=H.ID_HORARIO AND B.ACTIVO=1 AND D.ACTIVO=1 AND D.DIA_SEMANA=S.DIA_SEMANA)`;

export async function jornadasEmpleado(c: Connection, id: number): Promise<JornadaDia[]> {
  const r = await c.execute<JornadaDia>(
    `SELECT TO_CHAR(H.VIGENTE_DESDE,'YYYY-MM-DD') "desde",TO_CHAR(H.VIGENTE_HASTA,'YYYY-MM-DD') "hasta",D.DIA_SEMANA "dia",TO_CHAR(SUM(D.MINUTO_SALIDA+D.CRUZA_MEDIANOCHE*1440-D.MINUTO_ENTRADA-D.MINUTOS_DESCANSO)/60,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') "horas" FROM EMPLEADO_HORARIO H JOIN (${distribucionHorarioSql}) D ON D.ID_HORARIO=H.ID_HORARIO AND D.ACTIVO=1 WHERE H.ID_EMPLEADO=:id AND H.ACTIVO=1 AND D.LABORABLE=1 GROUP BY H.VIGENTE_DESDE,H.VIGENTE_HASTA,D.DIA_SEMANA ORDER BY H.VIGENTE_DESDE,D.DIA_SEMANA`,
    { id },
    { outFormat: oracledb.OUT_FORMAT_OBJECT },
  );
  return r.rows ?? [];
}
