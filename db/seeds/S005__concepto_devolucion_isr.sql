-- Reintegro del exceso realmente retenido al liquidar el ISR anual; no es renta nueva.
MERGE INTO CONCEPTOS_NOMINA destino
USING (SELECT 'ISR_DEVOLUCION' CODIGO, DATE '2026-01-01' VIGENTE_DESDE FROM DUAL) origen
ON (destino.CODIGO=origen.CODIGO AND destino.VIGENTE_DESDE=origen.VIGENTE_DESDE)
WHEN NOT MATCHED THEN INSERT (CODIGO,NOMBRE,NATURALEZA,AFECTA_IGSS,AFECTA_ISR,AFECTA_PRESTACIONES,VIGENTE_DESDE)
VALUES (origen.CODIGO,'Devolución ISR retenido en exceso','INGRESO',0,0,0,origen.VIGENTE_DESDE);
/
