MERGE INTO CENTROS_TRABAJO T USING (
 SELECT C.ID_CENTRO_TRABAJO,MIN(M.ID_MUNICIPIO_GT) ID_MUNICIPIO_GT
 FROM CENTROS_TRABAJO C CROSS JOIN MUNICIPIOS_GT M
 JOIN DEPARTAMENTOS_GT D ON D.ID_DEPARTAMENTO_GT=M.ID_DEPARTAMENTO_GT
 WHERE C.LOCALIDAD_ANTERIOR IS NOT NULL AND C.ID_MUNICIPIO_GT IS NULL
 AND (REGEXP_REPLACE(TRANSLATE(UPPER(C.LOCALIDAD_ANTERIOR),'ÁÉÍÓÚÜÑ','AEIOUUN'),'[^A-Z0-9]','') IN (REGEXP_REPLACE(TRANSLATE(UPPER(M.NOMBRE),'ÁÉÍÓÚÜÑ','AEIOUUN'),'[^A-Z0-9]',''),REGEXP_REPLACE(TRANSLATE(UPPER(M.NOMBRE||D.NOMBRE),'ÁÉÍÓÚÜÑ','AEIOUUN'),'[^A-Z0-9]',''),REGEXP_REPLACE(TRANSLATE(UPPER(D.NOMBRE||M.NOMBRE),'ÁÉÍÓÚÜÑ','AEIOUUN'),'[^A-Z0-9]',''))
 OR (M.CODIGO_INE='0101' AND REGEXP_REPLACE(TRANSLATE(UPPER(C.LOCALIDAD_ANTERIOR),'ÁÉÍÓÚÜÑ','AEIOUUN'),'[^A-Z0-9]','') IN ('GUATEMALACIUDAD','CIUDADDEGUATEMALA')))
 GROUP BY C.ID_CENTRO_TRABAJO HAVING COUNT(*)=1
) S ON (T.ID_CENTRO_TRABAJO=S.ID_CENTRO_TRABAJO)
WHEN MATCHED THEN UPDATE SET T.ID_MUNICIPIO_GT_PROPUESTO=S.ID_MUNICIPIO_GT WHERE T.ID_MUNICIPIO_GT_PROPUESTO IS NULL;
/
