CREATE TABLE PERMISOS_JEFATURA (
  ID_PERMISO_JEFATURA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_JEFATURA NUMBER NOT NULL REFERENCES JEFATURAS(ID_JEFATURA),
  CODIGO_PERMISO VARCHAR2(40) NOT NULL REFERENCES PERMISOS_EQUIPO(CODIGO),
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION TIMESTAMP,
  CONSTRAINT UQ_PERMISO_JEFATURA UNIQUE(ID_JEFATURA,CODIGO_PERMISO)
);
/
CREATE INDEX IX_PERMISO_JEF_CODIGO ON PERMISOS_JEFATURA(CODIGO_PERMISO);
