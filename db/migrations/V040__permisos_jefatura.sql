CREATE TABLE PERMISOS_EQUIPO (
  ID_PERMISO_EQUIPO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CODIGO VARCHAR2(40) NOT NULL UNIQUE CHECK (CODIGO IN ('VER_EQUIPO','VER_COMISIONES_EQUIPO','VER_VACACIONES_EQUIPO')),
  NOMBRE VARCHAR2(100) NOT NULL,
  DESCRIPCION VARCHAR2(500) NOT NULL,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION TIMESTAMP
);
/
