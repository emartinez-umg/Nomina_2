-- Apertura fiscal certificada: ingresos/retenciones reales anteriores a la implantación.
CREATE TABLE ISR_APERTURAS (
  ID_ISR_APERTURA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ANIO NUMBER(4) NOT NULL,
  FECHA_CORTE DATE NOT NULL,
  RENTA NUMBER(12,2) NOT NULL,
  IGSS NUMBER(12,2) NOT NULL,
  ISR NUMBER(12,2) NOT NULL,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ISR_APERTURAS PRIMARY KEY (ID_ISR_APERTURA),
  CONSTRAINT FK_ISR_APERTURA_EMP FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT UQ_ISR_APERTURA_EMP UNIQUE (ID_EMPLEADO,ANIO),
  CONSTRAINT CK_ISR_APERTURA_VAL CHECK (RENTA>=0 AND IGSS>=0 AND ISR>=0),
  CONSTRAINT CK_ISR_APERTURA_CORTE CHECK (ANIO BETWEEN 2000 AND 9999 AND EXTRACT(YEAR FROM FECHA_CORTE)=ANIO AND FECHA_CORTE=TRUNC(FECHA_CORTE) AND (EXTRACT(DAY FROM FECHA_CORTE)=15 OR FECHA_CORTE=LAST_DAY(FECHA_CORTE))),
  CONSTRAINT CK_ISR_APERTURA_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_ISR_APERTURA_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION>=FECHA_CREACION)
);
/
CREATE INDEX IX_ISR_APERTURA_ANIO ON ISR_APERTURAS (ANIO);
/
CREATE INDEX IX_ISR_APERTURA_CORTE ON ISR_APERTURAS (FECHA_CORTE);
/
CREATE INDEX IX_ISR_APERTURA_ACT ON ISR_APERTURAS (ACTIVO);
/
CREATE INDEX IX_ISR_APERTURA_FECHA ON ISR_APERTURAS (FECHA_CREACION);
/
CREATE OR REPLACE TRIGGER TR_ISR_APERTURA_MOD BEFORE UPDATE ON ISR_APERTURAS FOR EACH ROW BEGIN :NEW.FECHA_MODIFICACION:=CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE); END;
