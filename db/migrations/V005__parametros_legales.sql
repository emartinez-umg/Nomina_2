-- FASE 1: parametros legales.

-- Valores numéricos con vigencia, unidad y fundamento; tasas como porcentaje.
CREATE TABLE PARAMETROS_LEGALES (
  ID_PARAMETRO_LEGAL NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(60 CHAR) NOT NULL,
  NOMBRE VARCHAR2(150 CHAR) NOT NULL,
  VALOR NUMBER(18,6) NOT NULL,
  UNIDAD VARCHAR2(20 CHAR) NOT NULL,
  VIGENTE_DESDE DATE NOT NULL,
  VIGENTE_HASTA DATE,
  FUNDAMENTO VARCHAR2(500 CHAR) NOT NULL,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PARAMETROS_LEGALES PRIMARY KEY (ID_PARAMETRO_LEGAL),
  CONSTRAINT CK_PARAMETROS_LEGALES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_PARAMETROS_LEGALES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_PARAMETROS_LEGALES_1 CHECK (UNIDAD IN ('PORCENTAJE','QUETZALES','DIAS','HORAS','MESES','PERIODOS','MINUTOS','ANIOS','CANTIDAD')),
  CONSTRAINT CK_PARAMETROS_LEGALES_2 CHECK (VALOR >= 0),
  CONSTRAINT CK_PARAMETROS_LEGALES_3 CHECK (UNIDAD <> 'PORCENTAJE' OR VALOR <= 100),
  CONSTRAINT CK_PARAMETROS_LEGALES_4 CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE),
  CONSTRAINT UQ_PARAMETROS_LEGALES_1 UNIQUE (CODIGO, VIGENTE_DESDE)
);
/

CREATE INDEX IX_PARAMETROS_LEGALES_1 ON PARAMETROS_LEGALES (NOMBRE);
/

CREATE INDEX IX_PARAMETROS_LEGALES_2 ON PARAMETROS_LEGALES (UNIDAD);
/

CREATE INDEX IX_PARAMETROS_LEGALES_3 ON PARAMETROS_LEGALES (VIGENTE_DESDE);
/

CREATE INDEX IX_PARAMETROS_LEGALES_4 ON PARAMETROS_LEGALES (VIGENTE_HASTA);
/

CREATE INDEX IX_PARAMETROS_LEGALES_5 ON PARAMETROS_LEGALES (ACTIVO);
/

CREATE INDEX IX_PARAMETROS_LEGALES_6 ON PARAMETROS_LEGALES (FECHA_CREACION);
/

-- Escala marginal con cuota fija y vigencia; último límite superior nulo.
CREATE TABLE TRAMOS_ISR (
  ID_TRAMO_ISR NUMBER GENERATED ALWAYS AS IDENTITY,
  VIGENTE_DESDE DATE NOT NULL,
  VIGENTE_HASTA DATE,
  LIMITE_INFERIOR NUMBER(12,2) NOT NULL,
  LIMITE_SUPERIOR NUMBER(12,2),
  TASA_PORCENTAJE NUMBER(7,4) NOT NULL,
  CUOTA_FIJA NUMBER(12,2) NOT NULL,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_TRAMOS_ISR PRIMARY KEY (ID_TRAMO_ISR),
  CONSTRAINT CK_TRAMOS_ISR_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_TRAMOS_ISR_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_TRAMOS_ISR_1 CHECK (LIMITE_INFERIOR >= 0),
  CONSTRAINT CK_TRAMOS_ISR_2 CHECK (LIMITE_SUPERIOR IS NULL OR LIMITE_SUPERIOR > LIMITE_INFERIOR),
  CONSTRAINT CK_TRAMOS_ISR_3 CHECK (TASA_PORCENTAJE BETWEEN 0 AND 100),
  CONSTRAINT CK_TRAMOS_ISR_4 CHECK (CUOTA_FIJA >= 0),
  CONSTRAINT CK_TRAMOS_ISR_5 CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE),
  CONSTRAINT UQ_TRAMOS_ISR_1 UNIQUE (VIGENTE_DESDE, LIMITE_INFERIOR)
);
/

CREATE INDEX IX_TRAMOS_ISR_1 ON TRAMOS_ISR (VIGENTE_HASTA);
/

CREATE INDEX IX_TRAMOS_ISR_2 ON TRAMOS_ISR (LIMITE_INFERIOR);
/

CREATE INDEX IX_TRAMOS_ISR_3 ON TRAMOS_ISR (LIMITE_SUPERIOR);
/

CREATE INDEX IX_TRAMOS_ISR_4 ON TRAMOS_ISR (ACTIVO);
/

CREATE INDEX IX_TRAMOS_ISR_5 ON TRAMOS_ISR (FECHA_CREACION);
/

