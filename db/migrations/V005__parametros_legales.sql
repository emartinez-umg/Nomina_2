-- Soportes por empleado, año fiscal y tipo; IGSS de planilla se acumula aparte.
CREATE TABLE ISR_DEDUCCIONES_EMPLEADO (
  ID_DEDUCCION_ISR NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_TIPO_DEDUCCION_ISR NUMBER NOT NULL,
  ANIO NUMBER(4) NOT NULL,
  MONTO NUMBER(12,2) NOT NULL,
  REFERENCIA VARCHAR2(100 CHAR) NOT NULL,
  FECHA_COMPROBANTE DATE NOT NULL,
  RUTA_SOPORTE VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ISR_DEDUCCIONES_EMPLEADO PRIMARY KEY (ID_DEDUCCION_ISR),
  CONSTRAINT CK_ISR_DEDUCCIONES_EMPLEADO_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_ISR_DEDUCCIONES_EMPLEADO_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_ISR_DEDUCCIONES_EMPLEADO_1 CHECK (ANIO BETWEEN 2000 AND 9999),
  CONSTRAINT CK_ISR_DEDUCCIONES_EMPLEADO_2 CHECK (MONTO > 0),
  CONSTRAINT CK_ISR_DEDUCCIONES_EMPLEADO_3 CHECK (EXTRACT(YEAR FROM FECHA_COMPROBANTE) = ANIO),
  CONSTRAINT UQ_ISR_DEDUCCIONES_EMPLEADO_1 UNIQUE (ID_EMPLEADO, ANIO, ID_TIPO_DEDUCCION_ISR, REFERENCIA),
  CONSTRAINT FK_ISR_DEDUCCIONES_EMPLEADO_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_ISR_DEDUCCIONES_EMPLEADO_2 FOREIGN KEY (ID_TIPO_DEDUCCION_ISR) REFERENCES TIPOS_DEDUCCION_ISR (ID_TIPO_DEDUCCION_ISR)
);
/

CREATE INDEX IX_ISR_DEDUCCIONES_EMPLEADO_1 ON ISR_DEDUCCIONES_EMPLEADO (ID_TIPO_DEDUCCION_ISR);
/

CREATE INDEX IX_ISR_DEDUCCIONES_EMPLEADO_2 ON ISR_DEDUCCIONES_EMPLEADO (ANIO);
/

CREATE INDEX IX_ISR_DEDUCCIONES_EMPLEADO_3 ON ISR_DEDUCCIONES_EMPLEADO (FECHA_COMPROBANTE);
/

CREATE INDEX IX_ISR_DEDUCCIONES_EMPLEADO_4 ON ISR_DEDUCCIONES_EMPLEADO (ACTIVO);
/

CREATE INDEX IX_ISR_DEDUCCIONES_EMPLEADO_5 ON ISR_DEDUCCIONES_EMPLEADO (FECHA_CREACION);
