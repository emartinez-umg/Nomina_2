CREATE OR REPLACE TRIGGER TR_CONTRATO_FECHA_FIN BEFORE INSERT OR UPDATE ON TIPOS_CONTRATO FOR EACH ROW
BEGIN
 IF INSERTING THEN
   :NEW.REQUIERE_FECHA_FIN := NVL(:NEW.REQUIERE_FECHA_FIN,:NEW.REQUIERE_FIN);
 ELSIF UPDATING('REQUIERE_FIN') AND NOT UPDATING('REQUIERE_FECHA_FIN') THEN
   :NEW.REQUIERE_FECHA_FIN := :NEW.REQUIERE_FIN;
 END IF;
 :NEW.REQUIERE_FIN := :NEW.REQUIERE_FECHA_FIN;
END;
