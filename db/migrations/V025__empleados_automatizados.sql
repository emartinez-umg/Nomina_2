CREATE TABLE PARENTESCOS (
  ID_PARENTESCO NUMBER GENERATED ALWAYS AS IDENTITY,
  NOMBRE VARCHAR2(60 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PARENTESCOS PRIMARY KEY (ID_PARENTESCO),
  CONSTRAINT UQ_PARENTESCOS_NOMBRE UNIQUE (NOMBRE),
  CONSTRAINT CK_PARENTESCOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_PARENTESCOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION>=FECHA_CREACION),
  CONSTRAINT FK_PARENTESCOS_CREADOR FOREIGN KEY (CREADO_POR) REFERENCES USUARIOS,
  CONSTRAINT FK_PARENTESCOS_EDITOR FOREIGN KEY (MODIFICADO_POR) REFERENCES USUARIOS
);
/
