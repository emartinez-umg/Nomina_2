-- Datos institucionales para documentos; una fila activa.
CREATE TABLE CONFIGURACION_EMPRESA (
  ID_CONFIGURACION_EMPRESA NUMBER GENERATED ALWAYS AS IDENTITY,
  RAZON_SOCIAL VARCHAR2(200 CHAR) NOT NULL,
  NIT VARCHAR2(20 CHAR) NOT NULL,
  DIRECCION VARCHAR2(500 CHAR) NOT NULL,
  REPRESENTANTE VARCHAR2(200 CHAR),
  CORREO VARCHAR2(254 CHAR),
  TELEFONO VARCHAR2(8 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CONFIGURACION_EMPRESA PRIMARY KEY (ID_CONFIGURACION_EMPRESA),
  CONSTRAINT CK_CONFIGURACION_EMPRESA_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_CONFIGURACION_EMPRESA_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_CONFIGURACION_EMPRESA_1 CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{8}$')),
  CONSTRAINT UQ_CONFIGURACION_EMPRESA_1 UNIQUE (NIT)
);
/

CREATE INDEX IX_CONFIGURACION_EMPRESA_1 ON CONFIGURACION_EMPRESA (RAZON_SOCIAL);
/

CREATE INDEX IX_CONFIGURACION_EMPRESA_2 ON CONFIGURACION_EMPRESA (ACTIVO);
/

CREATE INDEX IX_CONFIGURACION_EMPRESA_3 ON CONFIGURACION_EMPRESA (FECHA_CREACION);
/

CREATE UNIQUE INDEX UQ_EMPRESA_ACTIVA ON CONFIGURACION_EMPRESA (CASE WHEN ACTIVO = 1 THEN 1 END);
/
