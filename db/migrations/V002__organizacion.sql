-- FASE 1: organizacion.

-- Unidades organizativas reales, sin departamentos ficticios.
CREATE TABLE DEPARTAMENTOS (
  ID_DEPARTAMENTO NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  DESCRIPCION VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_DEPARTAMENTOS PRIMARY KEY (ID_DEPARTAMENTO),
  CONSTRAINT CK_DEPARTAMENTOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_DEPARTAMENTOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT UQ_DEPARTAMENTOS_1 UNIQUE (CODIGO)
);
/

CREATE INDEX IX_DEPARTAMENTOS_1 ON DEPARTAMENTOS (NOMBRE);
/

CREATE INDEX IX_DEPARTAMENTOS_2 ON DEPARTAMENTOS (ACTIVO);
/

CREATE INDEX IX_DEPARTAMENTOS_3 ON DEPARTAMENTOS (FECHA_CREACION);
/

