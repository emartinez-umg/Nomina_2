  CONSTRAINT CK_BITACORA_AUDITORIA_2 CHECK (VALORES_NUEVOS IS JSON),
  CONSTRAINT CK_BITACORA_AUDITORIA_3 CHECK (ROL_CODIGO IN ('ADMIN','RH','EMPLEADO')),
  CONSTRAINT CK_BITACORA_AUDITORIA_4 CHECK (ACTIVO = 1 AND MODIFICADO_POR IS NULL AND FECHA_MODIFICACION IS NULL),
  CONSTRAINT FK_BITACORA_AUDITORIA_1 FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO),
