  CONSTRAINT CK_CARGA_MASIVA_FILAS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_CARGA_MASIVA_FILAS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_CARGA_MASIVA_FILAS_1 CHECK (NUMERO_FILA > 0),
  CONSTRAINT CK_CARGA_MASIVA_FILAS_2 CHECK (DATOS IS JSON),
  CONSTRAINT CK_CARGA_MASIVA_FILAS_3 CHECK (ERRORES IS JSON),
  CONSTRAINT CK_CARGA_MASIVA_FILAS_4 CHECK (ESTADO IN ('PENDIENTE','VALIDA','INVALIDA','IMPORTADA')),
  CONSTRAINT CK_CARGA_MASIVA_FILAS_5 CHECK (ESTADO <> 'IMPORTADA' OR ID_EMPLEADO IS NOT NULL),
  CONSTRAINT UQ_CARGA_MASIVA_FILAS_1 UNIQUE (ID_CARGA_MASIVA, NUMERO_FILA),
  CONSTRAINT FK_CARGA_MASIVA_FILAS_1 FOREIGN KEY (ID_CARGA_MASIVA) REFERENCES CARGAS_MASIVAS (ID_CARGA_MASIVA),
  CONSTRAINT FK_CARGA_MASIVA_FILAS_2 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO)
