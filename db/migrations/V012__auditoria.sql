-- Validación por fila y empleado creado; datos propuestos sin credenciales.
CREATE TABLE CARGA_MASIVA_FILAS (
  ID_CARGA_MASIVA_FILA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_CARGA_MASIVA NUMBER NOT NULL,
  NUMERO_FILA NUMBER(8) NOT NULL,
  DATOS CLOB NOT NULL,
  ERRORES CLOB NOT NULL,
  ID_EMPLEADO NUMBER,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
