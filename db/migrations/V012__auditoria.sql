-- Lote de importación y resultados; nunca guarda contraseñas temporales.
CREATE TABLE CARGAS_MASIVAS (
  ID_CARGA_MASIVA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_USUARIO NUMBER NOT NULL,
  NOMBRE_ARCHIVO VARCHAR2(200 CHAR) NOT NULL,
  SHA256 RAW(32) NOT NULL,
  MODALIDAD VARCHAR2(15 CHAR) NOT NULL,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'VALIDANDO' NOT NULL,
  TOTAL_FILAS NUMBER(8) DEFAULT 0 NOT NULL,
  FILAS_VALIDAS NUMBER(8) DEFAULT 0 NOT NULL,
  FILAS_IMPORTADAS NUMBER(8) DEFAULT 0 NOT NULL,
  CONFIRMADA_EN DATE,
  RUTA_REPORTE VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CARGAS_MASIVAS PRIMARY KEY (ID_CARGA_MASIVA),
  CONSTRAINT CK_CARGAS_MASIVAS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_CARGAS_MASIVAS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_CARGAS_MASIVAS_1 CHECK (MODALIDAD IN ('TODO_O_NADA','SOLO_VALIDAS')),
  CONSTRAINT CK_CARGAS_MASIVAS_2 CHECK (ESTADO IN ('VALIDANDO','VALIDADA','IMPORTADA','FALLIDA')),
  CONSTRAINT CK_CARGAS_MASIVAS_3 CHECK (TOTAL_FILAS >= 0 AND FILAS_VALIDAS BETWEEN 0 AND TOTAL_FILAS AND FILAS_IMPORTADAS BETWEEN 0 AND FILAS_VALIDAS),
  CONSTRAINT FK_CARGAS_MASIVAS_1 FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);
/

CREATE INDEX IX_CARGAS_MASIVAS_1 ON CARGAS_MASIVAS (ID_USUARIO);
