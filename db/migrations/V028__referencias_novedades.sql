-- V1-9: una referencia v0 puede repetirse entre empleados y quincenas.
-- Los originales mantienen su referencia; la clave solo protege las cargas v1.
ALTER TABLE NOVEDADES_MENSUALES ADD (CLAVE_REFERENCIA VARCHAR2(200 CHAR));
/

DROP INDEX UQ_NOV_MES_REFERENCIA;
/

UPDATE NOVEDADES_MENSUALES M SET CLAVE_REFERENCIA=TIPO||':'||TO_CHAR(ID_EMPLEADO,'TM9')||':'||TO_CHAR(MES,'YYYY-MM')||':'||REFERENCIA
WHERE REFERENCIA IS NOT NULL AND NOT EXISTS(SELECT 1 FROM NOVEDADES_ORIGEN O WHERE O.ID_NOVEDAD_MENSUAL=M.ID_NOVEDAD_MENSUAL);
/

CREATE UNIQUE INDEX UQ_NOV_MES_CLAVE_REF ON NOVEDADES_MENSUALES(CLAVE_REFERENCIA);
/
