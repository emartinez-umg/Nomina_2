-- V1-6. HORARIO_DIAS se conserva como archivo histórico de v0; los lectores usan bloques.
CREATE TABLE HORARIO_BLOQUES (
  ID_HORARIO_BLOQUE NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_HORARIO NUMBER NOT NULL,
  MINUTO_ENTRADA NUMBER(4) NOT NULL,
  MINUTO_SALIDA NUMBER(4) NOT NULL,
  CRUZA_MEDIANOCHE NUMBER(1) DEFAULT 0 NOT NULL,
  MINUTOS_DESCANSO NUMBER(4) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_HORARIO_BLOQUES PRIMARY KEY (ID_HORARIO_BLOQUE),
  CONSTRAINT FK_HB_HORARIO FOREIGN KEY (ID_HORARIO) REFERENCES HORARIOS(ID_HORARIO),
  CONSTRAINT FK_HB_CREADOR FOREIGN KEY (CREADO_POR) REFERENCES USUARIOS(ID_USUARIO),
  CONSTRAINT FK_HB_EDITOR FOREIGN KEY (MODIFICADO_POR) REFERENCES USUARIOS(ID_USUARIO),
  CONSTRAINT CK_HB_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_HB_HORAS CHECK (MINUTO_ENTRADA BETWEEN 0 AND 1439 AND MINUTO_SALIDA BETWEEN 0 AND 1439 AND CRUZA_MEDIANOCHE IN (0,1) AND MINUTOS_DESCANSO BETWEEN 0 AND 1439 AND MINUTO_SALIDA+1440*CRUZA_MEDIANOCHE-MINUTO_ENTRADA > MINUTOS_DESCANSO AND MINUTO_SALIDA+1440*CRUZA_MEDIANOCHE-MINUTO_ENTRADA <= 1440),
  CONSTRAINT CK_HB_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION)
);
/
CREATE INDEX IX_HB_HORARIO ON HORARIO_BLOQUES(ID_HORARIO);
/
CREATE INDEX IX_HB_CREADOR ON HORARIO_BLOQUES(CREADO_POR);
/
CREATE INDEX IX_HB_EDITOR ON HORARIO_BLOQUES(MODIFICADO_POR);
/
CREATE TABLE HORARIO_BLOQUE_DIAS (
  ID_HORARIO_BLOQUE_DIA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_HORARIO_BLOQUE NUMBER NOT NULL,
  DIA_SEMANA NUMBER(1) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_HORARIO_BLOQUE_DIAS PRIMARY KEY(ID_HORARIO_BLOQUE_DIA),
  CONSTRAINT UQ_HBD_DIA UNIQUE(ID_HORARIO_BLOQUE,DIA_SEMANA),
  CONSTRAINT FK_HBD_BLOQUE FOREIGN KEY(ID_HORARIO_BLOQUE) REFERENCES HORARIO_BLOQUES(ID_HORARIO_BLOQUE),
  CONSTRAINT FK_HBD_CREADOR FOREIGN KEY(CREADO_POR) REFERENCES USUARIOS(ID_USUARIO),
  CONSTRAINT FK_HBD_EDITOR FOREIGN KEY(MODIFICADO_POR) REFERENCES USUARIOS(ID_USUARIO),
  CONSTRAINT CK_HBD_DIA CHECK(DIA_SEMANA BETWEEN 1 AND 7),
  CONSTRAINT CK_HBD_ACT CHECK(ACTIVO IN (0,1)),
  CONSTRAINT CK_HBD_MOD CHECK(FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION)
);
/
CREATE INDEX IX_HBD_CREADOR ON HORARIO_BLOQUE_DIAS(CREADO_POR);
/
CREATE INDEX IX_HBD_EDITOR ON HORARIO_BLOQUE_DIAS(MODIFICADO_POR);
/
CREATE INDEX IX_HBD_DIA ON HORARIO_BLOQUE_DIAS(DIA_SEMANA);
/
DECLARE
  V_ID NUMBER;
BEGIN
  FOR B IN (SELECT ID_HORARIO,MINUTO_ENTRADA,MINUTO_SALIDA,CRUZA_MEDIANOCHE,MINUTOS_DESCANSO,MIN(CREADO_POR) CREADOR,MIN(FECHA_CREACION) FECHA FROM HORARIO_DIAS WHERE ACTIVO=1 AND LABORABLE=1 GROUP BY ID_HORARIO,MINUTO_ENTRADA,MINUTO_SALIDA,CRUZA_MEDIANOCHE,MINUTOS_DESCANSO) LOOP
    INSERT INTO HORARIO_BLOQUES(ID_HORARIO,MINUTO_ENTRADA,MINUTO_SALIDA,CRUZA_MEDIANOCHE,MINUTOS_DESCANSO,CREADO_POR,FECHA_CREACION) VALUES(B.ID_HORARIO,B.MINUTO_ENTRADA,B.MINUTO_SALIDA,B.CRUZA_MEDIANOCHE,B.MINUTOS_DESCANSO,B.CREADOR,B.FECHA) RETURNING ID_HORARIO_BLOQUE INTO V_ID;
    INSERT INTO HORARIO_BLOQUE_DIAS(ID_HORARIO_BLOQUE,DIA_SEMANA,CREADO_POR,FECHA_CREACION) SELECT V_ID,DIA_SEMANA,CREADO_POR,FECHA_CREACION FROM HORARIO_DIAS WHERE ACTIVO=1 AND LABORABLE=1 AND ID_HORARIO=B.ID_HORARIO AND MINUTO_ENTRADA=B.MINUTO_ENTRADA AND MINUTO_SALIDA=B.MINUTO_SALIDA AND CRUZA_MEDIANOCHE=B.CRUZA_MEDIANOCHE AND MINUTOS_DESCANSO=B.MINUTOS_DESCANSO;
  END LOOP;
END;
/
