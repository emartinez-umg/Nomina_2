CREATE TABLE MOTIVOS_BAJA (
  ID_MOTIVO_BAJA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL UNIQUE,
  CODIGO_ANTERIOR VARCHAR2(80 CHAR),
  NOMBRE VARCHAR2(50 CHAR) NOT NULL,
  NOMBRE_NORMALIZADO VARCHAR2(50 CHAR) NOT NULL,
  DESCRIPCION VARCHAR2(500 CHAR),
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1))
);
/
CREATE TABLE ZONAS (
  ID_ZONA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL UNIQUE,
  CODIGO_ANTERIOR VARCHAR2(80 CHAR),
  NOMBRE VARCHAR2(30 CHAR) NOT NULL,
  NOMBRE_NORMALIZADO VARCHAR2(30 CHAR) NOT NULL,
  CODIGO_POSTAL VARCHAR2(5 CHAR) NOT NULL CHECK (REGEXP_LIKE(CODIGO_POSTAL,'^[0-9]{5}$','c')),
  DESCRIPCION VARCHAR2(500 CHAR),
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1))
);
/
CREATE TABLE PAISES (
  ID_PAIS NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL UNIQUE,
  CODIGO_ANTERIOR VARCHAR2(80 CHAR),
  NOMBRE VARCHAR2(100 CHAR) NOT NULL,
  NOMBRE_NORMALIZADO VARCHAR2(100 CHAR) NOT NULL,
  CODIGO_ISO VARCHAR2(2 CHAR) NOT NULL UNIQUE CHECK (REGEXP_LIKE(CODIGO_ISO,'^[A-Z]{2}$','c')),
  DESCRIPCION VARCHAR2(500 CHAR),
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1))
);
/
DECLARE
BEGIN
  FOR T IN (
    SELECT 'MOTIVOS_BAJA' TABLA,'motivos-baja' ENTIDAD FROM DUAL UNION ALL
    SELECT 'ZONAS','zonas' FROM DUAL UNION ALL
    SELECT 'PAISES','paises' FROM DUAL
  ) LOOP
    INSERT INTO CONFIG_CODIGOS(ENTIDAD,LONGITUD_MAXIMA,PATRON) VALUES(T.ENTIDAD,3,'GENERICO');
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_'||T.TABLA||'_NOMBRE_NORM ON '||T.TABLA||'(NOMBRE_NORMALIZADO)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_NOMBRE ON '||T.TABLA||'(NOMBRE)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_DESCRIPCION ON '||T.TABLA||'(DESCRIPCION)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_ACTIVO ON '||T.TABLA||'(ACTIVO)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_FECHA ON '||T.TABLA||'(FECHA_CREACION)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_CREADOR ON '||T.TABLA||'(CREADO_POR)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_EDITOR ON '||T.TABLA||'(MODIFICADO_POR)';
    EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER TR_'||T.TABLA||'_NOMBRE_NORM BEFORE INSERT OR UPDATE OF NOMBRE,NOMBRE_NORMALIZADO ON '||T.TABLA||' FOR EACH ROW BEGIN :NEW.NOMBRE:=TRIM(REGEXP_REPLACE(:NEW.NOMBRE,''[[:space:]]+'','' '')); :NEW.NOMBRE_NORMALIZADO:=N2_NOMBRE_NORMALIZADO(:NEW.NOMBRE); END;';
    EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER TR_'||T.TABLA||'_CODIGO BEFORE INSERT OR UPDATE OF CODIGO ON '||T.TABLA||' FOR EACH ROW BEGIN IF INSERTING AND :NEW.CODIGO IS NULL THEN :NEW.CODIGO:=N2_CODIGOS.ASIGNAR('''||T.ENTIDAD||''',:NEW.NOMBRE,NULL,:NEW.FECHA_CREACION,NULL); ELSIF UPDATING AND (:NEW.CODIGO<>:OLD.CODIGO OR :NEW.CODIGO IS NULL) THEN RAISE_APPLICATION_ERROR(-20042,''El código es permanente.''); END IF; END;';
  END LOOP;
END;
