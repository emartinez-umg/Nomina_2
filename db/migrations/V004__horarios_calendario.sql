-- FASE 1: horarios calendario.

-- Patrón semanal; horas legales por jornada en parámetros.
CREATE TABLE HORARIOS (
  ID_HORARIO NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  DESCRIPCION VARCHAR2(500 CHAR),
  JORNADA VARCHAR2(10 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_HORARIOS PRIMARY KEY (ID_HORARIO),
  CONSTRAINT CK_HORARIOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_HORARIOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_HORARIOS_1 CHECK (JORNADA IN ('DIURNA','MIXTA','NOCTURNA')),
  CONSTRAINT UQ_HORARIOS_1 UNIQUE (CODIGO)
);
/

CREATE INDEX IX_HORARIOS_1 ON HORARIOS (NOMBRE);
/

CREATE INDEX IX_HORARIOS_2 ON HORARIOS (JORNADA);
/

CREATE INDEX IX_HORARIOS_3 ON HORARIOS (ACTIVO);
/

CREATE INDEX IX_HORARIOS_4 ON HORARIOS (FECHA_CREACION);
/

-- ISO lunes=1, domingo=7; minutos desde medianoche, con cruce nocturno.
CREATE TABLE HORARIO_DIAS (
  ID_HORARIO_DIA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_HORARIO NUMBER NOT NULL,
  DIA_SEMANA NUMBER(1) NOT NULL,
  LABORABLE NUMBER(1) DEFAULT 1 NOT NULL,
  MINUTO_ENTRADA NUMBER(4),
  MINUTO_SALIDA NUMBER(4),
  CRUZA_MEDIANOCHE NUMBER(1) DEFAULT 0 NOT NULL,
  MINUTOS_DESCANSO NUMBER(4) DEFAULT 0 NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_HORARIO_DIAS PRIMARY KEY (ID_HORARIO_DIA),
  CONSTRAINT CK_HORARIO_DIAS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_HORARIO_DIAS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_HORARIO_DIAS_1 CHECK (DIA_SEMANA BETWEEN 1 AND 7),
  CONSTRAINT CK_HORARIO_DIAS_2 CHECK (LABORABLE IN (0,1)),
  CONSTRAINT CK_HORARIO_DIAS_3 CHECK (CRUZA_MEDIANOCHE IN (0,1)),
  CONSTRAINT CK_HORARIO_DIAS_4 CHECK (MINUTO_ENTRADA BETWEEN 0 AND 1439),
  CONSTRAINT CK_HORARIO_DIAS_5 CHECK (MINUTO_SALIDA BETWEEN 0 AND 1439),
  CONSTRAINT CK_HORARIO_DIAS_6 CHECK (MINUTOS_DESCANSO BETWEEN 0 AND 1439),
  CONSTRAINT CK_HORARIO_DIAS_7 CHECK ((LABORABLE = 0 AND MINUTO_ENTRADA IS NULL AND MINUTO_SALIDA IS NULL AND CRUZA_MEDIANOCHE = 0 AND MINUTOS_DESCANSO = 0) OR (LABORABLE = 1 AND MINUTO_ENTRADA IS NOT NULL AND MINUTO_SALIDA IS NOT NULL AND MINUTO_SALIDA + CRUZA_MEDIANOCHE * 1440 - MINUTO_ENTRADA > MINUTOS_DESCANSO AND MINUTO_SALIDA + CRUZA_MEDIANOCHE * 1440 - MINUTO_ENTRADA <= 1440)),
  CONSTRAINT UQ_HORARIO_DIAS_1 UNIQUE (ID_HORARIO, DIA_SEMANA),
  CONSTRAINT FK_HORARIO_DIAS_1 FOREIGN KEY (ID_HORARIO) REFERENCES HORARIOS (ID_HORARIO)
);
/

CREATE INDEX IX_HORARIO_DIAS_1 ON HORARIO_DIAS (DIA_SEMANA);
/

CREATE INDEX IX_HORARIO_DIAS_2 ON HORARIO_DIAS (LABORABLE);
/

CREATE INDEX IX_HORARIO_DIAS_3 ON HORARIO_DIAS (ACTIVO);
/

CREATE INDEX IX_HORARIO_DIAS_4 ON HORARIO_DIAS (FECHA_CREACION);
/

-- Asignación de horario con vigencia.
CREATE TABLE EMPLEADO_HORARIO (
  ID_EMPLEADO_HORARIO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_HORARIO NUMBER NOT NULL,
  VIGENTE_DESDE DATE NOT NULL,
  VIGENTE_HASTA DATE,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_EMPLEADO_HORARIO PRIMARY KEY (ID_EMPLEADO_HORARIO),
  CONSTRAINT CK_EMPLEADO_HORARIO_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_EMPLEADO_HORARIO_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_EMPLEADO_HORARIO_1 CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE),
  CONSTRAINT UQ_EMPLEADO_HORARIO_1 UNIQUE (ID_EMPLEADO, VIGENTE_DESDE),
  CONSTRAINT FK_EMPLEADO_HORARIO_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_EMPLEADO_HORARIO_2 FOREIGN KEY (ID_HORARIO) REFERENCES HORARIOS (ID_HORARIO)
);
/

CREATE INDEX IX_EMPLEADO_HORARIO_1 ON EMPLEADO_HORARIO (ID_HORARIO);
/

CREATE INDEX IX_EMPLEADO_HORARIO_2 ON EMPLEADO_HORARIO (VIGENTE_DESDE);
/

CREATE INDEX IX_EMPLEADO_HORARIO_3 ON EMPLEADO_HORARIO (VIGENTE_HASTA);
/

CREATE INDEX IX_EMPLEADO_HORARIO_4 ON EMPLEADO_HORARIO (ACTIVO);
/

CREATE INDEX IX_EMPLEADO_HORARIO_5 ON EMPLEADO_HORARIO (FECHA_CREACION);
/

-- Fecha efectiva, fecha nominal, ámbito y franja para medios días.
CREATE TABLE FERIADOS (
  ID_FERIADO NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(60 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  FECHA DATE NOT NULL,
  FECHA_CONMEMORACION DATE NOT NULL,
  AMBITO VARCHAR2(10 CHAR) DEFAULT 'NACIONAL' NOT NULL,
  LOCALIDAD VARCHAR2(120 CHAR) DEFAULT '*' NOT NULL,
  MINUTO_INICIO NUMBER(4) DEFAULT 0 NOT NULL,
  MINUTO_FIN NUMBER(4) DEFAULT 1440 NOT NULL,
  FUNDAMENTO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_FERIADOS PRIMARY KEY (ID_FERIADO),
  CONSTRAINT CK_FERIADOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_FERIADOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_FERIADOS_1 CHECK (AMBITO IN ('NACIONAL','LOCAL')),
  CONSTRAINT CK_FERIADOS_2 CHECK ((AMBITO = 'NACIONAL' AND LOCALIDAD = '*') OR (AMBITO = 'LOCAL' AND LOCALIDAD <> '*')),
  CONSTRAINT CK_FERIADOS_3 CHECK (FECHA = TRUNC(FECHA)),
  CONSTRAINT CK_FERIADOS_4 CHECK (MINUTO_INICIO >= 0 AND MINUTO_FIN <= 1440 AND MINUTO_FIN > MINUTO_INICIO),
  CONSTRAINT UQ_FERIADOS_1 UNIQUE (CODIGO, FECHA_CONMEMORACION, LOCALIDAD),
  CONSTRAINT UQ_FERIADOS_2 UNIQUE (FECHA, LOCALIDAD, MINUTO_INICIO)
);
/

CREATE INDEX IX_FERIADOS_1 ON FERIADOS (FECHA_CONMEMORACION);
/

CREATE INDEX IX_FERIADOS_2 ON FERIADOS (AMBITO);
/

CREATE INDEX IX_FERIADOS_3 ON FERIADOS (LOCALIDAD);
/

CREATE INDEX IX_FERIADOS_4 ON FERIADOS (NOMBRE);
/

CREATE INDEX IX_FERIADOS_5 ON FERIADOS (ACTIVO);
/

CREATE INDEX IX_FERIADOS_6 ON FERIADOS (FECHA_CREACION);
/
