  END LOOP;
  FOR R IN (SELECT ID_EVENTO ID,FECHA_CREACION FROM EVENTOS ORDER BY FECHA_CREACION,ID_EVENTO) LOOP
    V_CODIGO:=N2_CODIGOS.ASIGNAR('eventos',NULL,NULL,R.FECHA_CREACION);
