CREATE OR REPLACE TRIGGER TR_PARAMETROS_LEGALES_CODIGO
BEFORE INSERT OR UPDATE OF CODIGO,CODIGO_ANTERIOR,CLAVE_INTERNA ON PARAMETROS_LEGALES FOR EACH ROW
BEGIN
  IF INSERTING THEN
    :NEW.CODIGO_ANTERIOR:=:NEW.CODIGO;
    -- Seeds entregan su clave original; versionar entrega el código ya reservado.
    IF :NEW.CLAVE_INTERNA IS NULL THEN
      :NEW.CLAVE_INTERNA:=:NEW.CODIGO;
      BEGIN
        SELECT LEGADO INTO :NEW.CLAVE_INTERNA FROM REGISTRO_CODIGOS WHERE ENTIDAD='parametros-legales' AND CODIGO=:NEW.CODIGO;
      EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
      :NEW.CLAVE_INTERNA:=NVL(:NEW.CLAVE_INTERNA,REPLACE(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(TRANSLATE(UPPER(:NEW.NOMBRE),'ÁÉÍÓÚÑÜÀÈÌÒÙÂÊÎÔÛÄËÏÖ','AEIOUNUAEIOUAEIOUAEIO'),'[^A-Z0-9 ]',''),' +',' ')),' ','_'));
    END IF;
    :NEW.CODIGO:=N2_CODIGOS.ASIGNAR('parametros-legales',:NEW.NOMBRE,NULL,:NEW.FECHA_CREACION,:NEW.CLAVE_INTERNA);
  ELSIF :NEW.CODIGO<>:OLD.CODIGO OR :NEW.CODIGO IS NULL OR NVL(:NEW.CODIGO_ANTERIOR,CHR(0))<>NVL(:OLD.CODIGO_ANTERIOR,CHR(0)) OR NVL(:NEW.CLAVE_INTERNA,CHR(0))<>:OLD.CLAVE_INTERNA THEN
    RAISE_APPLICATION_ERROR(-20042,'El código asignado y su clave interna son inmutables.');
  END IF;
END;
