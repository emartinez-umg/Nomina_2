CREATE OR REPLACE PACKAGE N2_CODIGOS AS
  FUNCTION GENERICO(P_PALABRA VARCHAR2,P_LONGITUD NUMBER DEFAULT 3,P_OPCION_B NUMBER DEFAULT 0) RETURN VARCHAR2;
  FUNCTION VISTA_PREVIA(P_ENTIDAD VARCHAR2,P_PALABRA VARCHAR2 DEFAULT NULL,P_DEPARTAMENTO NUMBER DEFAULT NULL,P_FECHA DATE DEFAULT NULL,P_LEGADO VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
  FUNCTION ASIGNAR(P_ENTIDAD VARCHAR2,P_PALABRA VARCHAR2 DEFAULT NULL,P_DEPARTAMENTO NUMBER DEFAULT NULL,P_FECHA DATE DEFAULT NULL,P_LEGADO VARCHAR2 DEFAULT NULL) RETURN VARCHAR2;
END;
/
CREATE OR REPLACE PACKAGE BODY N2_CODIGOS AS
  FUNCTION GENERICO(P_PALABRA VARCHAR2,P_LONGITUD NUMBER DEFAULT 3,P_OPCION_B NUMBER DEFAULT 0) RETURN VARCHAR2 IS
    LIMPIO VARCHAR2(4000); PALABRA VARCHAR2(4000); PRIMERA VARCHAR2(4000); INICIALES VARCHAR2(4000); I NUMBER:=1;
  BEGIN
    LIMPIO:=TRIM(REGEXP_REPLACE(REGEXP_REPLACE(TRANSLATE(UPPER(P_PALABRA),'ÁÉÍÓÚÑÜÀÈÌÒÙÂÊÎÔÛÄËÏÖ','AEIOUNUAEIOUAEIOUAEIO'),'[^A-Z0-9 ]',''),' +',' '));
    IF P_OPCION_B=1 THEN
      LIMPIO:=REPLACE(LIMPIO,' ','');
      RETURN SUBSTR(SUBSTR(LIMPIO,1,1)||REGEXP_REPLACE(SUBSTR(LIMPIO,2),'[AEIOU]',''),1,P_LONGITUD);
    END IF;
    IF INSTR(LIMPIO,' ')=0 THEN RETURN SUBSTR(LIMPIO,1,P_LONGITUD); END IF;
    LOOP
      PALABRA:=REGEXP_SUBSTR(LIMPIO,'[^ ]+',1,I); EXIT WHEN PALABRA IS NULL;
      IF PALABRA NOT IN ('DE','DEL','LA','LAS','EL','LOS','Y','E','EN','PARA','POR','CON','A') THEN
        IF PRIMERA IS NULL THEN PRIMERA:=PALABRA; END IF;
        INICIALES:=INICIALES||SUBSTR(PALABRA,1,1);
      END IF;
      I:=I+1;
    END LOOP;
    RETURN SUBSTR(CASE WHEN LENGTH(INICIALES)>=2 THEN INICIALES ELSE PRIMERA END,1,P_LONGITUD);
  END;
  FUNCTION VISTA_PREVIA(P_ENTIDAD VARCHAR2,P_PALABRA VARCHAR2 DEFAULT NULL,P_DEPARTAMENTO NUMBER DEFAULT NULL,P_FECHA DATE DEFAULT NULL,P_LEGADO VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    CFG CONFIG_CODIGOS%ROWTYPE; BASE VARCHAR2(80); CANDIDATO VARCHAR2(80); V_AMBITO VARCHAR2(80); N NUMBER; EXISTE NUMBER;
  BEGIN
    SELECT * INTO CFG FROM CONFIG_CODIGOS WHERE ENTIDAD=P_ENTIDAD;
    IF CFG.PATRON='GENERICO' THEN
      -- Todas las vigencias de un parámetro conservan su identidad y clave semántica.
      IF P_ENTIDAD='parametros-legales' AND P_LEGADO IS NOT NULL THEN
        BEGIN
          SELECT CODIGO INTO CANDIDATO FROM REGISTRO_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND (CODIGO=P_LEGADO OR LEGADO=P_LEGADO) FETCH FIRST 1 ROW ONLY;
          RETURN CANDIDATO;
        EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
      END IF;
      BASE:=GENERICO(P_PALABRA,CFG.LONGITUD_MAXIMA);
      IF BASE IS NULL THEN RAISE_APPLICATION_ERROR(-20041,'El nombre debe contener una palabra significativa para generar el código.'); END IF;
      CANDIDATO:=BASE;
      SELECT COUNT(*) INTO EXISTE FROM REGISTRO_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND CODIGO=CANDIDATO;
      IF EXISTE=0 THEN RETURN CANDIDATO; END IF;
      CANDIDATO:=GENERICO(P_PALABRA,CFG.LONGITUD_MAXIMA,1);
      SELECT COUNT(*) INTO EXISTE FROM REGISTRO_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND CODIGO=CANDIDATO;
      IF EXISTE=0 AND CANDIDATO IS NOT NULL THEN RETURN CANDIDATO; END IF;
      N:=2;
      LOOP
        CANDIDATO:=BASE||TO_CHAR(N,'TM9');
        SELECT COUNT(*) INTO EXISTE FROM REGISTRO_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND CODIGO=CANDIDATO;
        EXIT WHEN EXISTE=0; N:=N+1;
      END LOOP;
      RETURN CANDIDATO;
    END IF;
    IF CFG.PATRON='EMPLEADO' THEN
      SELECT CODIGO INTO BASE FROM DEPARTAMENTOS WHERE ID_DEPARTAMENTO=P_DEPARTAMENTO;
      V_AMBITO:=TO_CHAR(P_DEPARTAMENTO,'TM9'); BASE:=CFG.PREFIJO||'_'||BASE||'_';
    ELSE
      V_AMBITO:=TO_CHAR(NVL(P_FECHA,CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE)),'YYYY');
      BASE:=CFG.PREFIJO||'_'||V_AMBITO||'_';
    END IF;
    SELECT NVL(MAX(ULTIMO_NUMERO),0)+1 INTO N FROM SECUENCIAS_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND AMBITO=V_AMBITO;
    CANDIDATO:=TO_CHAR(N,'TM9');
    RETURN BASE||CASE WHEN LENGTH(CANDIDATO)<4 THEN LPAD(CANDIDATO,4,'0') ELSE CANDIDATO END;
  END;
  FUNCTION ASIGNAR(P_ENTIDAD VARCHAR2,P_PALABRA VARCHAR2 DEFAULT NULL,P_DEPARTAMENTO NUMBER DEFAULT NULL,P_FECHA DATE DEFAULT NULL,P_LEGADO VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 IS
    CFG CONFIG_CODIGOS%ROWTYPE; V_AMBITO VARCHAR2(80); N NUMBER; CANDIDATO VARCHAR2(80); EXISTE NUMBER;
  BEGIN
    SELECT * INTO CFG FROM CONFIG_CODIGOS WHERE ENTIDAD=P_ENTIDAD;
    V_AMBITO:=CASE CFG.PATRON WHEN 'GENERICO' THEN 'GENERAL' WHEN 'EMPLEADO' THEN TO_CHAR(P_DEPARTAMENTO,'TM9') ELSE TO_CHAR(NVL(P_FECHA,CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE)),'YYYY') END;
    BEGIN
      INSERT INTO SECUENCIAS_CODIGOS(ENTIDAD,AMBITO) VALUES(P_ENTIDAD,V_AMBITO);
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
    SELECT ULTIMO_NUMERO INTO N FROM SECUENCIAS_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND AMBITO=V_AMBITO FOR UPDATE;
    CANDIDATO:=VISTA_PREVIA(P_ENTIDAD,P_PALABRA,P_DEPARTAMENTO,P_FECHA,P_LEGADO);
    SELECT COUNT(*) INTO EXISTE FROM REGISTRO_CODIGOS WHERE ENTIDAD=P_ENTIDAD AND CODIGO=CANDIDATO;
    IF EXISTE=0 THEN
      INSERT INTO REGISTRO_CODIGOS(ENTIDAD,CODIGO,LEGADO) VALUES(P_ENTIDAD,CANDIDATO,P_LEGADO);
      UPDATE SECUENCIAS_CODIGOS SET ULTIMO_NUMERO=N+1 WHERE ENTIDAD=P_ENTIDAD AND AMBITO=V_AMBITO;
    END IF;
    RETURN CANDIDATO;
  END;
END;
