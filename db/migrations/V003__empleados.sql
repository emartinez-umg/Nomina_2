-- FASE 1: empleados.

-- Expediente y pertenencia organizativa; salario y horario por historial.
CREATE TABLE EMPLEADOS (
  ID_EMPLEADO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_USUARIO NUMBER,
  CODIGO VARCHAR2(40 CHAR) NOT NULL,
  NOMBRES VARCHAR2(100 CHAR) NOT NULL,
  APELLIDOS VARCHAR2(100 CHAR) NOT NULL,
  DPI VARCHAR2(13 CHAR) NOT NULL,
  NIT VARCHAR2(20 CHAR) NOT NULL,
  AFILIACION_IGSS VARCHAR2(20 CHAR),
  FECHA_NACIMIENTO DATE NOT NULL,
  SEXO VARCHAR2(1 CHAR) NOT NULL,
  ESTADO_CIVIL VARCHAR2(20 CHAR) NOT NULL,
  DIRECCION VARCHAR2(500 CHAR) NOT NULL,
  TELEFONO VARCHAR2(8 CHAR) NOT NULL,
  CORREO VARCHAR2(254 CHAR) NOT NULL,
  ID_BANCO NUMBER,
  CUENTA_BANCARIA VARCHAR2(34 CHAR),
  TIPO_CUENTA VARCHAR2(15 CHAR),
  ID_PUESTO NUMBER NOT NULL,
  ID_DEPARTAMENTO NUMBER NOT NULL,
  ID_JEFATURA NUMBER,
  ID_TIPO_CONTRATO NUMBER NOT NULL,
  ID_CENTRO_TRABAJO NUMBER NOT NULL,
  FECHA_INGRESO DATE NOT NULL,
  FECHA_FIN_CONTRATO DATE,
  FECHA_EGRESO DATE,
  MOTIVO_EGRESO VARCHAR2(500 CHAR),
  ESTADO VARCHAR2(15 CHAR) DEFAULT 'ACTIVO' NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_EMPLEADOS PRIMARY KEY (ID_EMPLEADO),
  CONSTRAINT CK_EMPLEADOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_EMPLEADOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_EMPLEADOS_1 CHECK (REGEXP_LIKE(DPI, '^[0-9]{13}$')),
  CONSTRAINT CK_EMPLEADOS_2 CHECK (REGEXP_LIKE(NIT, '^[0-9]+-[0-9K]$')),
  CONSTRAINT CK_EMPLEADOS_3 CHECK (REGEXP_LIKE(AFILIACION_IGSS, '^[0-9]+$')),
  CONSTRAINT CK_EMPLEADOS_4 CHECK (SEXO IN ('F','M','O')),
  CONSTRAINT CK_EMPLEADOS_5 CHECK (ESTADO_CIVIL IN ('SOLTERO','CASADO','UNIDO','DIVORCIADO','VIUDO')),
  CONSTRAINT CK_EMPLEADOS_6 CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{8}$')),
  CONSTRAINT CK_EMPLEADOS_7 CHECK (CORREO = LOWER(TRIM(CORREO)) AND INSTR(CORREO, '@') > 1),
  CONSTRAINT CK_EMPLEADOS_8 CHECK (TIPO_CUENTA IN ('AHORRO','MONETARIA')),
  CONSTRAINT CK_EMPLEADOS_9 CHECK ((ID_BANCO IS NULL AND CUENTA_BANCARIA IS NULL AND TIPO_CUENTA IS NULL) OR (ID_BANCO IS NOT NULL AND CUENTA_BANCARIA IS NOT NULL AND TIPO_CUENTA IS NOT NULL)),
  CONSTRAINT CK_EMPLEADOS_10 CHECK (ESTADO IN ('ACTIVO','SUSPENDIDO','EGRESADO')),
  CONSTRAINT CK_EMPLEADOS_11 CHECK (FECHA_NACIMIENTO < FECHA_INGRESO),
  CONSTRAINT CK_EMPLEADOS_12 CHECK (FECHA_EGRESO IS NULL OR FECHA_EGRESO >= FECHA_INGRESO),
  CONSTRAINT CK_EMPLEADOS_13 CHECK (FECHA_FIN_CONTRATO IS NULL OR FECHA_FIN_CONTRATO >= FECHA_INGRESO),
  CONSTRAINT CK_EMPLEADOS_14 CHECK ((ESTADO = 'EGRESADO' AND FECHA_EGRESO IS NOT NULL AND MOTIVO_EGRESO IS NOT NULL) OR (ESTADO <> 'EGRESADO' AND FECHA_EGRESO IS NULL)),
  CONSTRAINT UQ_EMPLEADOS_1 UNIQUE (CODIGO),
  CONSTRAINT UQ_EMPLEADOS_2 UNIQUE (DPI),
  CONSTRAINT UQ_EMPLEADOS_3 UNIQUE (NIT),
  CONSTRAINT UQ_EMPLEADOS_4 UNIQUE (AFILIACION_IGSS),
  CONSTRAINT UQ_EMPLEADOS_5 UNIQUE (CORREO),
  CONSTRAINT UQ_EMPLEADOS_6 UNIQUE (ID_USUARIO),
  CONSTRAINT FK_EMPLEADOS_1 FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO),
  CONSTRAINT FK_EMPLEADOS_2 FOREIGN KEY (ID_BANCO) REFERENCES BANCOS (ID_BANCO),
  CONSTRAINT FK_EMPLEADOS_3 FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES DEPARTAMENTOS (ID_DEPARTAMENTO),
  CONSTRAINT FK_EMPLEADOS_4 FOREIGN KEY (ID_PUESTO, ID_DEPARTAMENTO) REFERENCES PUESTOS (ID_PUESTO, ID_DEPARTAMENTO),
  CONSTRAINT FK_EMPLEADOS_5 FOREIGN KEY (ID_JEFATURA, ID_DEPARTAMENTO) REFERENCES JEFATURAS (ID_JEFATURA, ID_DEPARTAMENTO),
  CONSTRAINT FK_EMPLEADOS_6 FOREIGN KEY (ID_TIPO_CONTRATO) REFERENCES TIPOS_CONTRATO (ID_TIPO_CONTRATO),
  CONSTRAINT FK_EMPLEADOS_7 FOREIGN KEY (ID_CENTRO_TRABAJO) REFERENCES CENTROS_TRABAJO (ID_CENTRO_TRABAJO)
);
/

