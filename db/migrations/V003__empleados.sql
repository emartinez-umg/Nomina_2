-- Varios contactos por empleado; prioridad única.
CREATE TABLE EMPLEADO_CONTACTOS_EMERGENCIA (
  ID_CONTACTO_EMERGENCIA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  NOMBRE VARCHAR2(200 CHAR) NOT NULL,
  PARENTESCO VARCHAR2(60 CHAR) NOT NULL,
  TELEFONO VARCHAR2(8 CHAR) NOT NULL,
  PRIORIDAD NUMBER(2) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_EMPLEADO_CONTACTOS_EMERGENCIA PRIMARY KEY (ID_CONTACTO_EMERGENCIA),
  CONSTRAINT CK_EMPLEADO_CONTACTOS_EMERGENCIA_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_EMPLEADO_CONTACTOS_EMERGENCIA_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_EMPLEADO_CONTACTOS_EMERGENCIA_1 CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{8}$')),
  CONSTRAINT CK_EMPLEADO_CONTACTOS_EMERGENCIA_2 CHECK (PRIORIDAD BETWEEN 1 AND 99),
  CONSTRAINT UQ_EMPLEADO_CONTACTOS_EMERGENCIA_1 UNIQUE (ID_EMPLEADO, PRIORIDAD),
  CONSTRAINT FK_EMPLEADO_CONTACTOS_EMERGENCIA_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO)
);
/

CREATE INDEX IX_EMPLEADO_CONTACTOS_EMERGENCIA_1 ON EMPLEADO_CONTACTOS_EMERGENCIA (NOMBRE);
/

CREATE INDEX IX_EMPLEADO_CONTACTOS_EMERGENCIA_2 ON EMPLEADO_CONTACTOS_EMERGENCIA (PARENTESCO);
/

CREATE INDEX IX_EMPLEADO_CONTACTOS_EMERGENCIA_3 ON EMPLEADO_CONTACTOS_EMERGENCIA (ACTIVO);
/

CREATE INDEX IX_EMPLEADO_CONTACTOS_EMERGENCIA_4 ON EMPLEADO_CONTACTOS_EMERGENCIA (FECHA_CREACION);
/

-- Salario mensual vigente; no se duplica en empleados.
CREATE TABLE HISTORIAL_SALARIAL (
  ID_HISTORIAL_SALARIAL NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  SALARIO_BASE NUMBER(12,2) NOT NULL,
  VIGENTE_DESDE DATE NOT NULL,
  VIGENTE_HASTA DATE,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_HISTORIAL_SALARIAL PRIMARY KEY (ID_HISTORIAL_SALARIAL),
  CONSTRAINT CK_HISTORIAL_SALARIAL_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_HISTORIAL_SALARIAL_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_HISTORIAL_SALARIAL_1 CHECK (SALARIO_BASE > 0),
  CONSTRAINT CK_HISTORIAL_SALARIAL_2 CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE),
  CONSTRAINT UQ_HISTORIAL_SALARIAL_1 UNIQUE (ID_EMPLEADO, VIGENTE_DESDE),
  CONSTRAINT FK_HISTORIAL_SALARIAL_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO)
);
/

CREATE INDEX IX_HISTORIAL_SALARIAL_1 ON HISTORIAL_SALARIAL (VIGENTE_DESDE);
/

CREATE INDEX IX_HISTORIAL_SALARIAL_2 ON HISTORIAL_SALARIAL (VIGENTE_HASTA);
/

CREATE INDEX IX_HISTORIAL_SALARIAL_3 ON HISTORIAL_SALARIAL (SALARIO_BASE);
/

CREATE INDEX IX_HISTORIAL_SALARIAL_4 ON HISTORIAL_SALARIAL (ACTIVO);
/

CREATE INDEX IX_HISTORIAL_SALARIAL_5 ON HISTORIAL_SALARIAL (FECHA_CREACION);
