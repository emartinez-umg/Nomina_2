-- Quincenas exactas, no superponibles por fecha inicial única y límites rígidos.
CREATE TABLE PERIODOS_NOMINA (
  ID_PERIODO_NOMINA NUMBER GENERATED ALWAYS AS IDENTITY,
  FECHA_INICIO DATE NOT NULL,
  FECHA_FIN DATE NOT NULL,
  QUINCENA NUMBER(1) NOT NULL,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'ABIERTO' NOT NULL,
  VERSION_CALCULO NUMBER(5) DEFAULT 0 NOT NULL,
  CALCULADO_EN DATE,
  REVISADO_EN DATE,
  APROBADO_EN DATE,
  CERRADO_EN DATE,
  APROBADO_POR NUMBER,
  CERRADO_POR NUMBER,
  MOTIVO_REAPERTURA VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PERIODOS_NOMINA PRIMARY KEY (ID_PERIODO_NOMINA),
  CONSTRAINT CK_PERIODOS_NOMINA_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_PERIODOS_NOMINA_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_PERIODOS_NOMINA_1 CHECK (QUINCENA IN (1,2)),
  CONSTRAINT CK_PERIODOS_NOMINA_2 CHECK (FECHA_INICIO = TRUNC(FECHA_INICIO) AND FECHA_FIN = TRUNC(FECHA_FIN)),
  CONSTRAINT CK_PERIODOS_NOMINA_3 CHECK ((QUINCENA = 1 AND EXTRACT(DAY FROM FECHA_INICIO) = 1 AND FECHA_FIN = FECHA_INICIO + 14) OR (QUINCENA = 2 AND EXTRACT(DAY FROM FECHA_INICIO) = 16 AND FECHA_FIN = LAST_DAY(FECHA_INICIO))),
  CONSTRAINT CK_PERIODOS_NOMINA_4 CHECK (ESTADO IN ('ABIERTO','CALCULADO','REVISADO','APROBADO','CERRADO')),
  CONSTRAINT CK_PERIODOS_NOMINA_5 CHECK (VERSION_CALCULO >= 0),
  CONSTRAINT CK_PERIODOS_NOMINA_6 CHECK (ESTADO <> 'CERRADO' OR (CERRADO_EN IS NOT NULL AND CERRADO_POR IS NOT NULL)),
  CONSTRAINT CK_PERIODOS_NOMINA_7 CHECK (ESTADO NOT IN ('APROBADO','CERRADO') OR (APROBADO_EN IS NOT NULL AND APROBADO_POR IS NOT NULL)),
  CONSTRAINT UQ_PERIODOS_NOMINA_1 UNIQUE (FECHA_INICIO),
  CONSTRAINT FK_PERIODOS_NOMINA_1 FOREIGN KEY (APROBADO_POR) REFERENCES USUARIOS (ID_USUARIO),
  CONSTRAINT FK_PERIODOS_NOMINA_2 FOREIGN KEY (CERRADO_POR) REFERENCES USUARIOS (ID_USUARIO)
);
/

