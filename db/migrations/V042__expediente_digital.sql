CREATE TABLE EXPEDIENTE_DOCUMENTOS (
  ID_EXPEDIENTE_DOCUMENTO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_EMPLEADO NUMBER NOT NULL REFERENCES EMPLEADOS(ID_EMPLEADO),
  ID_TIPO_DOCUMENTO_EXPEDIENTE NUMBER NOT NULL REFERENCES TIPOS_DOCUMENTO_EXPEDIENTE(ID_TIPO_DOCUMENTO_EXPEDIENTE),
  VERSION NUMBER(8) NOT NULL CHECK (VERSION>0),
  ES_ACTUAL NUMBER(1) DEFAULT 1 NOT NULL CHECK (ES_ACTUAL IN (0,1)),
  NOMBRE_ARCHIVO VARCHAR2(200) NOT NULL,
  CLAVE_ARCHIVO VARCHAR2(68) NOT NULL UNIQUE CHECK (REGEXP_LIKE(CLAVE_ARCHIVO,'^[a-f0-9]{64}\.bin$')),
  TIPO_CONTENIDO VARCHAR2(20) NOT NULL CHECK (TIPO_CONTENIDO IN ('application/pdf','image/jpeg','image/png')),
  TAMANO_BYTES NUMBER(10) NOT NULL CHECK (TAMANO_BYTES>0),
  HASH_SHA256 VARCHAR2(64) NOT NULL CHECK (REGEXP_LIKE(HASH_SHA256,'^[a-f0-9]{64}$')),
  VENCIMIENTO DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  MOTIVO_BAJA VARCHAR2(500),
  BAJA_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  BAJA_EN TIMESTAMP,
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION TIMESTAMP,
  CONSTRAINT UQ_EXP_VERSION UNIQUE(ID_EMPLEADO,ID_TIPO_DOCUMENTO_EXPEDIENTE,VERSION),
  CONSTRAINT CK_EXP_BAJA CHECK (ACTIVO=1 OR (MOTIVO_BAJA IS NOT NULL AND BAJA_EN IS NOT NULL AND BAJA_POR IS NOT NULL AND ES_ACTUAL=0))
);
/
CREATE UNIQUE INDEX UQ_EXP_ACTUAL ON EXPEDIENTE_DOCUMENTOS (
  CASE WHEN ACTIVO=1 AND ES_ACTUAL=1 THEN ID_EMPLEADO END,
  CASE WHEN ACTIVO=1 AND ES_ACTUAL=1 THEN ID_TIPO_DOCUMENTO_EXPEDIENTE END
);
/
CREATE INDEX IX_EXP_EMPLEADO_TIPO ON EXPEDIENTE_DOCUMENTOS(ID_EMPLEADO,ID_TIPO_DOCUMENTO_EXPEDIENTE,ACTIVO,ES_ACTUAL);
