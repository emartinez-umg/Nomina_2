-- B7: clasificación independiente del efecto salarial; los históricos conservan sus importes.
ALTER TABLE TIPOS_AUSENCIA ADD CATEGORIA_INASISTENCIA VARCHAR2(25 CHAR);
/
UPDATE TIPOS_AUSENCIA SET CATEGORIA_INASISTENCIA=CASE
 WHEN NVL(CODIGO_ANTERIOR,CODIGO)='INJUSTIFICADA' THEN 'SIN_JUSTIFICAR'
 WHEN EFECTO='SUBSIDIO_IGSS' THEN 'IGSS_JUSTIFICADA'
 WHEN EFECTO='CON_GOCE' THEN 'JUSTIFICADA_CON_GOCE'
 ELSE 'JUSTIFICADA_SIN_GOCE' END;
/
-- Compatible con seeds y clientes anteriores: solo deriva la categoría cuando no la indican.
CREATE OR REPLACE TRIGGER TR_TA_CATEGORIA
BEFORE INSERT OR UPDATE ON TIPOS_AUSENCIA FOR EACH ROW
BEGIN
 IF :NEW.CATEGORIA_INASISTENCIA IS NULL THEN
  :NEW.CATEGORIA_INASISTENCIA:=CASE WHEN NVL(:NEW.CODIGO_ANTERIOR,:NEW.CODIGO)='INJUSTIFICADA' THEN 'SIN_JUSTIFICAR' WHEN :NEW.EFECTO='SUBSIDIO_IGSS' THEN 'IGSS_JUSTIFICADA' WHEN :NEW.EFECTO='CON_GOCE' THEN 'JUSTIFICADA_CON_GOCE' ELSE 'JUSTIFICADA_SIN_GOCE' END;
 END IF;
END;
/
ALTER TABLE TIPOS_AUSENCIA MODIFY CATEGORIA_INASISTENCIA NOT NULL;
/
ALTER TABLE TIPOS_AUSENCIA ADD CONSTRAINT CK_TA_CATEGORIA CHECK(CATEGORIA_INASISTENCIA IN ('IGSS_JUSTIFICADA','JUSTIFICADA_CON_GOCE','JUSTIFICADA_SIN_GOCE','SIN_JUSTIFICAR'));
/
INSERT INTO TIPOS_AUSENCIA(NOMBRE,EFECTO,CATEGORIA_INASISTENCIA,DESCRIPCION)
SELECT 'Inasistencia sin justificación','SIN_GOCE','SIN_JUSTIFICAR','Inasistencia no justificada; descuenta salario en nómina.' FROM DUAL
WHERE NOT EXISTS(SELECT 1 FROM TIPOS_AUSENCIA WHERE NOMBRE_NORMALIZADO=N2_NOMBRE_NORMALIZADO('Inasistencia sin justificación'));
/
