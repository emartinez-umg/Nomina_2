CREATE TABLE PAGOS_NOMINA (
 ID_PAGO_NOMINA NUMBER GENERATED ALWAYS AS IDENTITY,
 ID_EMPLEADO NUMBER NOT NULL, MES DATE NOT NULL, TIPO_PAGO VARCHAR2(8 CHAR) NOT NULL,
 ID_NOMINA_EMPLEADO NUMBER NOT NULL, ESTADO VARCHAR2(9 CHAR) DEFAULT 'PAGADO' NOT NULL,
 MOTIVO_REVERSION VARCHAR2(500 CHAR), REVERTIDO_POR NUMBER, REVERTIDO_EN DATE,
 CREADO_POR NUMBER, FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
 MODIFICADO_POR NUMBER, FECHA_MODIFICACION DATE, ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
 CONSTRAINT PK_PAGOS_NOMINA PRIMARY KEY(ID_PAGO_NOMINA),
 CONSTRAINT UQ_PAGO_PERSONA_MES_TIPO UNIQUE(ID_EMPLEADO,MES,TIPO_PAGO),
 CONSTRAINT UQ_PAGO_RESULTADO UNIQUE(ID_NOMINA_EMPLEADO),
 CONSTRAINT FK_PAGO_PERSONA FOREIGN KEY(ID_EMPLEADO) REFERENCES EMPLEADOS(ID_EMPLEADO),
 CONSTRAINT FK_PAGO_RESULTADO FOREIGN KEY(ID_NOMINA_EMPLEADO,ID_EMPLEADO) REFERENCES NOMINA_EMPLEADO(ID_NOMINA_EMPLEADO,ID_EMPLEADO),
 CONSTRAINT CK_PAGOS_NOMINA_ACT CHECK(ACTIVO IN (0,1)),
 CONSTRAINT CK_PAGOS_NOMINA_MOD CHECK(FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION>=FECHA_CREACION),
 CONSTRAINT CK_PAGOS_NOMINA_1 CHECK(MES=TRUNC(MES,'MM') AND TIPO_PAGO IN ('ANTICIPO','PAGO') AND ESTADO IN ('PAGADO','REVERTIDO')),
 CONSTRAINT CK_PAGOS_NOMINA_2 CHECK(ESTADO='PAGADO' OR (REVERTIDO_POR IS NOT NULL AND REVERTIDO_EN IS NOT NULL AND MOTIVO_REVERSION IS NOT NULL))
);
/
