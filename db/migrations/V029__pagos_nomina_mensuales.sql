-- Mismo importe y cantidad; solo se espacia el calendario pendiente. Pagadas intactas.
BEGIN
 FOR D IN (SELECT DISTINCT ID_DESCUENTO_EMPLEADO FROM DESCUENTOS_CUOTAS WHERE ACTIVO=1 AND ESTADO IN ('PENDIENTE','PARCIAL')) LOOP
  DECLARE V_MES DATE; V_N NUMBER:=0; BEGIN
   SELECT TRUNC(MIN(FECHA_VENCIMIENTO),'MM') INTO V_MES FROM DESCUENTOS_CUOTAS WHERE ID_DESCUENTO_EMPLEADO=D.ID_DESCUENTO_EMPLEADO AND ACTIVO=1 AND ESTADO IN ('PENDIENTE','PARCIAL');
   FOR C IN (SELECT ID_DESCUENTO_CUOTA FROM DESCUENTOS_CUOTAS WHERE ID_DESCUENTO_EMPLEADO=D.ID_DESCUENTO_EMPLEADO AND ACTIVO=1 AND ESTADO IN ('PENDIENTE','PARCIAL') ORDER BY NUMERO_CUOTA) LOOP
    UPDATE DESCUENTOS_CUOTAS SET FECHA_VENCIMIENTO_ANTERIOR=FECHA_VENCIMIENTO,FECHA_VENCIMIENTO=LAST_DAY(ADD_MONTHS(V_MES,V_N)) WHERE ID_DESCUENTO_CUOTA=C.ID_DESCUENTO_CUOTA;
    V_N:=V_N+1;
   END LOOP;
   UPDATE DESCUENTOS_EMPLEADO SET FECHA_FIN_ANTERIOR=FECHA_FIN,FECHA_FIN=(SELECT MAX(FECHA_VENCIMIENTO) FROM DESCUENTOS_CUOTAS WHERE ID_DESCUENTO_EMPLEADO=D.ID_DESCUENTO_EMPLEADO AND ACTIVO=1) WHERE ID_DESCUENTO_EMPLEADO=D.ID_DESCUENTO_EMPLEADO AND MODALIDAD<>'FIJO';
  END;
 END LOOP;
END;
