-- FASE 1: descuentos prestamos.

-- Préstamo, anticipo, embargo, parqueo, consumo en tienda y otros.
CREATE TABLE TIPOS_DESCUENTO (
  ID_TIPO_DESCUENTO NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  DESCRIPCION VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_TIPOS_DESCUENTO PRIMARY KEY (ID_TIPO_DESCUENTO),
  CONSTRAINT CK_TIPOS_DESCUENTO_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_TIPOS_DESCUENTO_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT UQ_TIPOS_DESCUENTO_1 UNIQUE (CODIGO)
);
/

CREATE INDEX IX_TIPOS_DESCUENTO_1 ON TIPOS_DESCUENTO (NOMBRE);
/

CREATE INDEX IX_TIPOS_DESCUENTO_2 ON TIPOS_DESCUENTO (ACTIVO);
/

CREATE INDEX IX_TIPOS_DESCUENTO_3 ON TIPOS_DESCUENTO (FECHA_CREACION);
/

-- Acuerdo de descuento; cuotas, fijo o único con saldo controlado.
CREATE TABLE DESCUENTOS_EMPLEADO (
  ID_DESCUENTO_EMPLEADO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_TIPO_DESCUENTO NUMBER NOT NULL,
  MODALIDAD VARCHAR2(10 CHAR) NOT NULL,
  MONTO_QUINCENA NUMBER(12,2) NOT NULL,
  MONTO_TOTAL NUMBER(12,2),
  SALDO NUMBER(12,2),
  NUMERO_CUOTAS NUMBER(5),
  FECHA_INICIO DATE NOT NULL,
  FECHA_FIN DATE,
  ESTADO VARCHAR2(15 CHAR) DEFAULT 'VIGENTE' NOT NULL,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_DESCUENTOS_EMPLEADO PRIMARY KEY (ID_DESCUENTO_EMPLEADO),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_1 CHECK (MODALIDAD IN ('FIJO','CUOTAS','UNICO')),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_2 CHECK (MONTO_QUINCENA > 0),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_3 CHECK (MONTO_TOTAL > 0),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_4 CHECK (SALDO >= 0 AND SALDO <= MONTO_TOTAL),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_5 CHECK (NUMERO_CUOTAS > 0),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_6 CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_7 CHECK (ESTADO IN ('VIGENTE','LIQUIDADO','CANCELADO')),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_8 CHECK ((MODALIDAD = 'FIJO' AND MONTO_TOTAL IS NULL AND SALDO IS NULL AND NUMERO_CUOTAS IS NULL) OR (MODALIDAD IN ('CUOTAS','UNICO') AND MONTO_TOTAL IS NOT NULL AND SALDO IS NOT NULL AND NUMERO_CUOTAS IS NOT NULL AND MONTO_QUINCENA <= MONTO_TOTAL)),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_9 CHECK (MODALIDAD <> 'UNICO' OR NUMERO_CUOTAS = 1),
  CONSTRAINT CK_DESCUENTOS_EMPLEADO_10 CHECK (ESTADO <> 'LIQUIDADO' OR SALDO = 0),
  CONSTRAINT UQ_DESCUENTOS_EMPLEADO_1 UNIQUE (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO),
  CONSTRAINT FK_DESCUENTOS_EMPLEADO_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_DESCUENTOS_EMPLEADO_2 FOREIGN KEY (ID_TIPO_DESCUENTO) REFERENCES TIPOS_DESCUENTO (ID_TIPO_DESCUENTO)
);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_1 ON DESCUENTOS_EMPLEADO (ID_EMPLEADO);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_2 ON DESCUENTOS_EMPLEADO (ID_TIPO_DESCUENTO);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_3 ON DESCUENTOS_EMPLEADO (MODALIDAD);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_4 ON DESCUENTOS_EMPLEADO (ESTADO);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_5 ON DESCUENTOS_EMPLEADO (FECHA_INICIO);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_6 ON DESCUENTOS_EMPLEADO (FECHA_FIN);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_7 ON DESCUENTOS_EMPLEADO (ACTIVO);
/

CREATE INDEX IX_DESCUENTOS_EMPLEADO_8 ON DESCUENTOS_EMPLEADO (FECHA_CREACION);
/

-- Origen de un descuento en cuotas; importe total incluye interés acordado.
CREATE TABLE PRESTAMOS (
  ID_PRESTAMO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_DESCUENTO_EMPLEADO NUMBER NOT NULL,
  ID_EMPLEADO NUMBER NOT NULL,
  CAPITAL NUMBER(12,2) NOT NULL,
  INTERES_TOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
  FECHA_DESEMBOLSO DATE NOT NULL,
  REFERENCIA VARCHAR2(100 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PRESTAMOS PRIMARY KEY (ID_PRESTAMO),
  CONSTRAINT CK_PRESTAMOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_PRESTAMOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_PRESTAMOS_1 CHECK (CAPITAL > 0),
  CONSTRAINT CK_PRESTAMOS_2 CHECK (INTERES_TOTAL >= 0),
  CONSTRAINT UQ_PRESTAMOS_1 UNIQUE (ID_DESCUENTO_EMPLEADO),
  CONSTRAINT UQ_PRESTAMOS_2 UNIQUE (REFERENCIA),
  CONSTRAINT FK_PRESTAMOS_1 FOREIGN KEY (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO) REFERENCES DESCUENTOS_EMPLEADO (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO),
  CONSTRAINT FK_PRESTAMOS_2 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO)
);
/

CREATE INDEX IX_PRESTAMOS_1 ON PRESTAMOS (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO);
/

CREATE INDEX IX_PRESTAMOS_2 ON PRESTAMOS (ID_EMPLEADO);
/

CREATE INDEX IX_PRESTAMOS_3 ON PRESTAMOS (FECHA_DESEMBOLSO);
/

CREATE INDEX IX_PRESTAMOS_4 ON PRESTAMOS (ACTIVO);
/

CREATE INDEX IX_PRESTAMOS_5 ON PRESTAMOS (FECHA_CREACION);
/

-- Calendario y saldo por cuota; periodo y nómina vinculados en V007.
CREATE TABLE DESCUENTOS_CUOTAS (
  ID_DESCUENTO_CUOTA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_DESCUENTO_EMPLEADO NUMBER NOT NULL,
  ID_EMPLEADO NUMBER NOT NULL,
  NUMERO_CUOTA NUMBER(5) NOT NULL,
  FECHA_VENCIMIENTO DATE NOT NULL,
  MONTO NUMBER(12,2) NOT NULL,
  MONTO_PAGADO NUMBER(12,2) DEFAULT 0 NOT NULL,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_PAGO DATE,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_DESCUENTOS_CUOTAS PRIMARY KEY (ID_DESCUENTO_CUOTA),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_1 CHECK (NUMERO_CUOTA > 0),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_2 CHECK (MONTO > 0),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_3 CHECK (MONTO_PAGADO BETWEEN 0 AND MONTO),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_4 CHECK (ESTADO IN ('PENDIENTE','PARCIAL','PAGADA','CANCELADA')),
  CONSTRAINT CK_DESCUENTOS_CUOTAS_5 CHECK ((ESTADO = 'PENDIENTE' AND MONTO_PAGADO = 0 AND FECHA_PAGO IS NULL) OR (ESTADO = 'PARCIAL' AND MONTO_PAGADO > 0 AND MONTO_PAGADO < MONTO AND FECHA_PAGO IS NOT NULL) OR (ESTADO = 'PAGADA' AND MONTO_PAGADO = MONTO AND FECHA_PAGO IS NOT NULL) OR ESTADO = 'CANCELADA'),
  CONSTRAINT UQ_DESCUENTOS_CUOTAS_1 UNIQUE (ID_DESCUENTO_EMPLEADO, NUMERO_CUOTA),
  CONSTRAINT UQ_DESCUENTOS_CUOTAS_2 UNIQUE (ID_DESCUENTO_CUOTA, ID_EMPLEADO),
  CONSTRAINT FK_DESCUENTOS_CUOTAS_1 FOREIGN KEY (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO) REFERENCES DESCUENTOS_EMPLEADO (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO),
  CONSTRAINT FK_DESCUENTOS_CUOTAS_2 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO)
);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_1 ON DESCUENTOS_CUOTAS (ID_DESCUENTO_EMPLEADO, ID_EMPLEADO);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_2 ON DESCUENTOS_CUOTAS (ID_EMPLEADO);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_3 ON DESCUENTOS_CUOTAS (ESTADO);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_4 ON DESCUENTOS_CUOTAS (FECHA_VENCIMIENTO);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_5 ON DESCUENTOS_CUOTAS (FECHA_PAGO);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_6 ON DESCUENTOS_CUOTAS (ACTIVO);
/

CREATE INDEX IX_DESCUENTOS_CUOTAS_7 ON DESCUENTOS_CUOTAS (FECHA_CREACION);
