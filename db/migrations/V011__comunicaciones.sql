-- FASE 1: comunicaciones.

-- Publicaciones con vigencia y destinatarios todos o grupos.
CREATE TABLE ANUNCIOS (
  ID_ANUNCIO NUMBER GENERATED ALWAYS AS IDENTITY,
  TITULO VARCHAR2(200 CHAR) NOT NULL,
  CONTENIDO CLOB NOT NULL,
  VIGENTE_DESDE DATE NOT NULL,
  VIGENTE_HASTA DATE NOT NULL,
  PARA_TODOS NUMBER(1) DEFAULT 1 NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ANUNCIOS PRIMARY KEY (ID_ANUNCIO),
  CONSTRAINT CK_ANUNCIOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_ANUNCIOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_ANUNCIOS_1 CHECK (VIGENTE_HASTA >= VIGENTE_DESDE),
  CONSTRAINT CK_ANUNCIOS_2 CHECK (PARA_TODOS IN (0,1))
);
/

CREATE INDEX IX_ANUNCIOS_1 ON ANUNCIOS (TITULO);
/

CREATE INDEX IX_ANUNCIOS_2 ON ANUNCIOS (VIGENTE_DESDE);
/

CREATE INDEX IX_ANUNCIOS_3 ON ANUNCIOS (VIGENTE_HASTA);
/

CREATE INDEX IX_ANUNCIOS_4 ON ANUNCIOS (PARA_TODOS);
/

CREATE INDEX IX_ANUNCIOS_5 ON ANUNCIOS (ACTIVO);
/

CREATE INDEX IX_ANUNCIOS_6 ON ANUNCIOS (FECHA_CREACION);
/

-- Agenda con inicio y fin local y audiencia segmentable.
CREATE TABLE EVENTOS (
  ID_EVENTO NUMBER GENERATED ALWAYS AS IDENTITY,
  TITULO VARCHAR2(200 CHAR) NOT NULL,
  DESCRIPCION CLOB,
  FECHA_INICIO DATE NOT NULL,
  FECHA_FIN DATE NOT NULL,
  LUGAR VARCHAR2(250 CHAR) NOT NULL,
  PARA_TODOS NUMBER(1) DEFAULT 1 NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_EVENTOS PRIMARY KEY (ID_EVENTO),
  CONSTRAINT CK_EVENTOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_EVENTOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_EVENTOS_1 CHECK (FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_EVENTOS_2 CHECK (PARA_TODOS IN (0,1))
);
/

CREATE INDEX IX_EVENTOS_1 ON EVENTOS (TITULO);
/

CREATE INDEX IX_EVENTOS_2 ON EVENTOS (FECHA_INICIO);
/

CREATE INDEX IX_EVENTOS_3 ON EVENTOS (FECHA_FIN);
/

CREATE INDEX IX_EVENTOS_4 ON EVENTOS (LUGAR);
/

CREATE INDEX IX_EVENTOS_5 ON EVENTOS (PARA_TODOS);
/

CREATE INDEX IX_EVENTOS_6 ON EVENTOS (ACTIVO);
/

CREATE INDEX IX_EVENTOS_7 ON EVENTOS (FECHA_CREACION);
/

-- Cada fila representa un grupo; varios grupos se unen por OR.
CREATE TABLE ANUNCIO_DESTINATARIOS (
  ID_ANUNCIO_DESTINATARIO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_ANUNCIO NUMBER NOT NULL,
  ID_DEPARTAMENTO NUMBER,
  ID_PUESTO NUMBER,
  ID_JEFATURA NUMBER,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ANUNCIO_DESTINATARIOS PRIMARY KEY (ID_ANUNCIO_DESTINATARIO),
  CONSTRAINT CK_ANUNCIO_DESTINATARIOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_ANUNCIO_DESTINATARIOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_ANUNCIO_DESTINATARIOS_1 CHECK ((CASE WHEN ID_DEPARTAMENTO IS NULL THEN 0 ELSE 1 END + CASE WHEN ID_PUESTO IS NULL THEN 0 ELSE 1 END + CASE WHEN ID_JEFATURA IS NULL THEN 0 ELSE 1 END) = 1),
  CONSTRAINT FK_ANUNCIO_DESTINATARIOS_1 FOREIGN KEY (ID_ANUNCIO) REFERENCES ANUNCIOS (ID_ANUNCIO),
  CONSTRAINT FK_ANUNCIO_DESTINATARIOS_2 FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES DEPARTAMENTOS (ID_DEPARTAMENTO),
  CONSTRAINT FK_ANUNCIO_DESTINATARIOS_3 FOREIGN KEY (ID_PUESTO) REFERENCES PUESTOS (ID_PUESTO),
  CONSTRAINT FK_ANUNCIO_DESTINATARIOS_4 FOREIGN KEY (ID_JEFATURA) REFERENCES JEFATURAS (ID_JEFATURA)
);
/

CREATE INDEX IX_ANUNCIO_DESTINATARIOS_1 ON ANUNCIO_DESTINATARIOS (ID_ANUNCIO);
/

CREATE INDEX IX_ANUNCIO_DESTINATARIOS_2 ON ANUNCIO_DESTINATARIOS (ID_DEPARTAMENTO);
/

CREATE INDEX IX_ANUNCIO_DESTINATARIOS_3 ON ANUNCIO_DESTINATARIOS (ID_PUESTO);
/

CREATE INDEX IX_ANUNCIO_DESTINATARIOS_4 ON ANUNCIO_DESTINATARIOS (ID_JEFATURA);
/

CREATE INDEX IX_ANUNCIO_DESTINATARIOS_5 ON ANUNCIO_DESTINATARIOS (ACTIVO);
