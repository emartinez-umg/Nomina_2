-- Campana por usuario y evento, lectura y vínculo al recurso protegido.
CREATE TABLE NOTIFICACIONES (
  ID_NOTIFICACION NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_USUARIO NUMBER NOT NULL,
  TIPO VARCHAR2(20 CHAR) NOT NULL,
  TITULO VARCHAR2(200 CHAR) NOT NULL,
  MENSAJE VARCHAR2(1000 CHAR) NOT NULL,
  CLAVE_EVENTO VARCHAR2(120 CHAR) NOT NULL,
  ID_SOLICITUD NUMBER,
  ID_DOCUMENTO_GENERADO NUMBER,
  ID_ANUNCIO NUMBER,
  ID_EVENTO NUMBER,
  LEIDA_EN DATE,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_NOTIFICACIONES PRIMARY KEY (ID_NOTIFICACION),
  CONSTRAINT CK_NOTIFICACIONES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_NOTIFICACIONES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_NOTIFICACIONES_1 CHECK (TIPO IN ('NUEVA_SOLICITUD','CAMBIO_ESTADO','DOCUMENTO_ENTREGADO','ANUNCIO','EVENTO')),
  CONSTRAINT CK_NOTIFICACIONES_2 CHECK (LEIDA_EN IS NULL OR LEIDA_EN >= FECHA_CREACION),
  CONSTRAINT UQ_NOTIFICACIONES_1 UNIQUE (ID_USUARIO, CLAVE_EVENTO),
  CONSTRAINT FK_NOTIFICACIONES_1 FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO),
  CONSTRAINT FK_NOTIFICACIONES_2 FOREIGN KEY (ID_SOLICITUD) REFERENCES SOLICITUDES (ID_SOLICITUD),
  CONSTRAINT FK_NOTIFICACIONES_3 FOREIGN KEY (ID_DOCUMENTO_GENERADO) REFERENCES DOCUMENTOS_GENERADOS (ID_DOCUMENTO_GENERADO),
  CONSTRAINT FK_NOTIFICACIONES_4 FOREIGN KEY (ID_ANUNCIO) REFERENCES ANUNCIOS (ID_ANUNCIO),
  CONSTRAINT FK_NOTIFICACIONES_5 FOREIGN KEY (ID_EVENTO) REFERENCES EVENTOS (ID_EVENTO)
);
/

CREATE INDEX IX_NOTIFICACIONES_1 ON NOTIFICACIONES (ID_SOLICITUD);
/

CREATE INDEX IX_NOTIFICACIONES_2 ON NOTIFICACIONES (ID_DOCUMENTO_GENERADO);
/

CREATE INDEX IX_NOTIFICACIONES_3 ON NOTIFICACIONES (ID_ANUNCIO);
/

CREATE INDEX IX_NOTIFICACIONES_4 ON NOTIFICACIONES (ID_EVENTO);
/

CREATE INDEX IX_NOTIFICACIONES_5 ON NOTIFICACIONES (TIPO);
/

CREATE INDEX IX_NOTIFICACIONES_6 ON NOTIFICACIONES (LEIDA_EN);
/

CREATE INDEX IX_NOTIFICACIONES_7 ON NOTIFICACIONES (ACTIVO);
