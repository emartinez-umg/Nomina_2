CREATE TABLE DEPARTAMENTOS_GT (
  ID_DEPARTAMENTO_GT NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO_INE VARCHAR2(2 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_DEPARTAMENTOS_GT PRIMARY KEY (ID_DEPARTAMENTO_GT),
  CONSTRAINT UQ_DEPARTAMENTOS_GT_INE UNIQUE (CODIGO_INE),
  CONSTRAINT UQ_DEPARTAMENTOS_GT_NOMBRE UNIQUE (NOMBRE),
  CONSTRAINT FK_DEPARTAMENTOS_GT_CREADOR FOREIGN KEY (CREADO_POR) REFERENCES USUARIOS,
  CONSTRAINT FK_DEPARTAMENTOS_GT_EDITOR FOREIGN KEY (MODIFICADO_POR) REFERENCES USUARIOS,
  CONSTRAINT CK_DEPARTAMENTOS_GT_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_DEPARTAMENTOS_GT_ACT CHECK (ACTIVO IN (0,1))
);
/
CREATE INDEX IX_DEPARTAMENTOS_GT_ACT ON DEPARTAMENTOS_GT (ACTIVO);
/
CREATE INDEX IX_DEPARTAMENTOS_GT_CREADOR ON DEPARTAMENTOS_GT (CREADO_POR);
/
CREATE INDEX IX_DEPARTAMENTOS_GT_EDITOR ON DEPARTAMENTOS_GT (MODIFICADO_POR);
/
CREATE OR REPLACE TRIGGER TR_DEPARTAMENTOS_GT_MOD
BEFORE UPDATE ON DEPARTAMENTOS_GT FOR EACH ROW
BEGIN
  :NEW.FECHA_MODIFICACION := CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE);
END;
/
CREATE TABLE MUNICIPIOS_GT (
  ID_MUNICIPIO_GT NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_DEPARTAMENTO_GT NUMBER NOT NULL,
  CODIGO_INE VARCHAR2(4 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_MUNICIPIOS_GT PRIMARY KEY (ID_MUNICIPIO_GT),
  CONSTRAINT FK_MUNICIPIOS_GT_DEP FOREIGN KEY (ID_DEPARTAMENTO_GT) REFERENCES DEPARTAMENTOS_GT,
  CONSTRAINT UQ_MUNICIPIOS_GT_INE UNIQUE (CODIGO_INE),
  CONSTRAINT UQ_MUNICIPIOS_GT_DEP_NOM UNIQUE (ID_DEPARTAMENTO_GT,NOMBRE),
  CONSTRAINT UQ_MUNICIPIOS_GT_PAR UNIQUE (ID_MUNICIPIO_GT,ID_DEPARTAMENTO_GT),
  CONSTRAINT FK_MUNICIPIOS_GT_CREADOR FOREIGN KEY (CREADO_POR) REFERENCES USUARIOS,
  CONSTRAINT FK_MUNICIPIOS_GT_EDITOR FOREIGN KEY (MODIFICADO_POR) REFERENCES USUARIOS,
  CONSTRAINT CK_MUNICIPIOS_GT_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_MUNICIPIOS_GT_ACT CHECK (ACTIVO IN (0,1))
);
/
CREATE INDEX IX_MUNICIPIOS_GT_NOMBRE ON MUNICIPIOS_GT (NOMBRE);
/
CREATE INDEX IX_MUNICIPIOS_GT_ACT ON MUNICIPIOS_GT (ACTIVO);
/
CREATE INDEX IX_MUNICIPIOS_GT_CREADOR ON MUNICIPIOS_GT (CREADO_POR);
/
CREATE INDEX IX_MUNICIPIOS_GT_EDITOR ON MUNICIPIOS_GT (MODIFICADO_POR);
/
CREATE OR REPLACE TRIGGER TR_MUNICIPIOS_GT_MOD
BEFORE UPDATE ON MUNICIPIOS_GT FOR EACH ROW
BEGIN
  :NEW.FECHA_MODIFICACION := CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE);
END;
