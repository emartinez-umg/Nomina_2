-- Transiciones de la solicitud con actor, fecha y motivo.
CREATE TABLE SOLICITUD_HISTORIAL (
  ID_SOLICITUD_HISTORIAL NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_SOLICITUD NUMBER NOT NULL,
  ESTADO_ANTERIOR VARCHAR2(12 CHAR),
  ESTADO_NUEVO VARCHAR2(12 CHAR) NOT NULL,
  ID_USUARIO NUMBER NOT NULL,
  FECHA DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MOTIVO VARCHAR2(1000 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_SOLICITUD_HISTORIAL PRIMARY KEY (ID_SOLICITUD_HISTORIAL),
  CONSTRAINT CK_SOLICITUD_HISTORIAL_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_SOLICITUD_HISTORIAL_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_SOLICITUD_HISTORIAL_1 CHECK (ESTADO_ANTERIOR IN ('EN_PROCESO','APROBADA','RECHAZADA','ENTREGADA')),
  CONSTRAINT CK_SOLICITUD_HISTORIAL_2 CHECK (ESTADO_NUEVO IN ('EN_PROCESO','APROBADA','RECHAZADA','ENTREGADA')),
  CONSTRAINT CK_SOLICITUD_HISTORIAL_3 CHECK ((ESTADO_ANTERIOR IS NULL AND ESTADO_NUEVO = 'EN_PROCESO') OR (ESTADO_ANTERIOR = 'EN_PROCESO' AND ESTADO_NUEVO IN ('APROBADA','RECHAZADA')) OR (ESTADO_ANTERIOR = 'APROBADA' AND ESTADO_NUEVO = 'ENTREGADA')),
  CONSTRAINT CK_SOLICITUD_HISTORIAL_4 CHECK (ESTADO_NUEVO <> 'RECHAZADA' OR MOTIVO IS NOT NULL),
  CONSTRAINT FK_SOLICITUD_HISTORIAL_1 FOREIGN KEY (ID_SOLICITUD) REFERENCES SOLICITUDES (ID_SOLICITUD),
  CONSTRAINT FK_SOLICITUD_HISTORIAL_2 FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);
/

CREATE INDEX IX_SOLICITUD_HISTORIAL_1 ON SOLICITUD_HISTORIAL (ID_SOLICITUD);
/

CREATE INDEX IX_SOLICITUD_HISTORIAL_2 ON SOLICITUD_HISTORIAL (ID_USUARIO);
/

