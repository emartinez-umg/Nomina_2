-- FASE 1: solicitudes documentos.

-- Trámites del portal y requerimiento de documento/PDF.
CREATE TABLE TIPOS_SOLICITUD (
  ID_TIPO_SOLICITUD NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  DESCRIPCION VARCHAR2(500 CHAR),
  GENERA_PDF NUMBER(1) DEFAULT 0 NOT NULL,
  ES_DIRECTA NUMBER(1) DEFAULT 0 NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_TIPOS_SOLICITUD PRIMARY KEY (ID_TIPO_SOLICITUD),
  CONSTRAINT CK_TIPOS_SOLICITUD_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_TIPOS_SOLICITUD_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_TIPOS_SOLICITUD_1 CHECK (GENERA_PDF IN (0,1)),
  CONSTRAINT CK_TIPOS_SOLICITUD_2 CHECK (ES_DIRECTA IN (0,1)),
  CONSTRAINT UQ_TIPOS_SOLICITUD_1 UNIQUE (CODIGO)
);
/

CREATE INDEX IX_TIPOS_SOLICITUD_1 ON TIPOS_SOLICITUD (NOMBRE);
/

CREATE INDEX IX_TIPOS_SOLICITUD_2 ON TIPOS_SOLICITUD (ACTIVO);
/

CREATE INDEX IX_TIPOS_SOLICITUD_3 ON TIPOS_SOLICITUD (FECHA_CREACION);
/

-- Bandeja común, datos críticos propuestos y resolución motivada.
CREATE TABLE SOLICITUDES (
  ID_SOLICITUD NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_TIPO_SOLICITUD NUMBER NOT NULL,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'EN_PROCESO' NOT NULL,
  DATOS_SOLICITADOS CLOB,
  OBSERVACIONES VARCHAR2(1000 CHAR),
  RESUELTO_POR NUMBER,
  RESUELTO_EN DATE,
  MOTIVO_RECHAZO VARCHAR2(500 CHAR),
  ENTREGADA_EN DATE,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_SOLICITUDES PRIMARY KEY (ID_SOLICITUD),
  CONSTRAINT CK_SOLICITUDES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_SOLICITUDES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_SOLICITUDES_1 CHECK (ESTADO IN ('EN_PROCESO','APROBADA','RECHAZADA','ENTREGADA')),
  CONSTRAINT CK_SOLICITUDES_2 CHECK (DATOS_SOLICITADOS IS JSON),
  CONSTRAINT CK_SOLICITUDES_3 CHECK (ESTADO <> 'RECHAZADA' OR MOTIVO_RECHAZO IS NOT NULL),
  CONSTRAINT CK_SOLICITUDES_4 CHECK (ESTADO = 'EN_PROCESO' OR (RESUELTO_POR IS NOT NULL AND RESUELTO_EN IS NOT NULL)),
  CONSTRAINT CK_SOLICITUDES_5 CHECK (ESTADO <> 'ENTREGADA' OR ENTREGADA_EN IS NOT NULL),
  CONSTRAINT UQ_SOLICITUDES_1 UNIQUE (ID_SOLICITUD, ID_EMPLEADO),
  CONSTRAINT FK_SOLICITUDES_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_SOLICITUDES_2 FOREIGN KEY (ID_TIPO_SOLICITUD) REFERENCES TIPOS_SOLICITUD (ID_TIPO_SOLICITUD),
  CONSTRAINT FK_SOLICITUDES_3 FOREIGN KEY (RESUELTO_POR) REFERENCES USUARIOS (ID_USUARIO)
);
/

CREATE INDEX IX_SOLICITUDES_1 ON SOLICITUDES (ID_EMPLEADO);
