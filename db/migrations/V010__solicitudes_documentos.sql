-- PDF privado por solicitud o boleta; snapshot de plantilla y hash del archivo.
CREATE TABLE DOCUMENTOS_GENERADOS (
  ID_DOCUMENTO_GENERADO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_SOLICITUD NUMBER,
  ID_NOMINA_EMPLEADO NUMBER,
  ID_PERIODO_NOMINA NUMBER,
  ID_PLANTILLA_DOCUMENTO NUMBER,
  VERSION NUMBER(5) NOT NULL,
  NOMBRE_ARCHIVO VARCHAR2(200 CHAR) NOT NULL,
  RUTA_PRIVADA VARCHAR2(500 CHAR) NOT NULL,
  SHA256 RAW(32) NOT NULL,
  TAMANIO_BYTES NUMBER(12) NOT NULL,
  CONTENIDO_PLANTILLA CLOB,
  VARIABLES_APLICADAS CLOB NOT NULL,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'VISTA_PREVIA' NOT NULL,
  ENTREGADO_EN DATE,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_DOCUMENTOS_GENERADOS PRIMARY KEY (ID_DOCUMENTO_GENERADO),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_1 CHECK (VERSION > 0),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_2 CHECK (TAMANIO_BYTES > 0),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_3 CHECK (VARIABLES_APLICADAS IS JSON),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_4 CHECK (ESTADO IN ('VISTA_PREVIA','ENTREGADO','ANULADO')),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_5 CHECK (ESTADO <> 'ENTREGADO' OR ENTREGADO_EN IS NOT NULL),
  CONSTRAINT CK_DOCUMENTOS_GENERADOS_6 CHECK ((ID_SOLICITUD IS NOT NULL AND ID_NOMINA_EMPLEADO IS NULL AND ID_PERIODO_NOMINA IS NULL AND ID_PLANTILLA_DOCUMENTO IS NOT NULL AND CONTENIDO_PLANTILLA IS NOT NULL) OR (ID_SOLICITUD IS NULL AND ID_NOMINA_EMPLEADO IS NOT NULL AND ID_PERIODO_NOMINA IS NOT NULL)),
  CONSTRAINT UQ_DOCUMENTOS_GENERADOS_1 UNIQUE (RUTA_PRIVADA),
  CONSTRAINT FK_DOCUMENTOS_GENERADOS_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_DOCUMENTOS_GENERADOS_2 FOREIGN KEY (ID_SOLICITUD, ID_EMPLEADO) REFERENCES SOLICITUDES (ID_SOLICITUD, ID_EMPLEADO),
  CONSTRAINT FK_DOCUMENTOS_GENERADOS_3 FOREIGN KEY (ID_NOMINA_EMPLEADO, ID_EMPLEADO, ID_PERIODO_NOMINA) REFERENCES NOMINA_EMPLEADO (ID_NOMINA_EMPLEADO, ID_EMPLEADO, ID_PERIODO_NOMINA),
  CONSTRAINT FK_DOCUMENTOS_GENERADOS_4 FOREIGN KEY (ID_PERIODO_NOMINA) REFERENCES PERIODOS_NOMINA (ID_PERIODO_NOMINA),
  CONSTRAINT FK_DOCUMENTOS_GENERADOS_5 FOREIGN KEY (ID_PLANTILLA_DOCUMENTO) REFERENCES PLANTILLAS_DOCUMENTO (ID_PLANTILLA_DOCUMENTO)
);
/

