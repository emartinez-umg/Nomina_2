-- Las acumulaciones v0 siguen intactas como respaldo. Una compensación explícita
-- conserva el disponible al corte si sus snapshots/tasas difieren de la tasa A9.
-- La apertura certificada se conserva; no se modifican solicitudes ni débitos.
DECLARE
  corte DATE;
  apertura DATE;
  aniversario DATE;
  tasa NUMBER;
  valor_mes NUMBER;
  anterior NUMBER;
  nuevo NUMBER;
  diferencia NUMBER;
  cantidad NUMBER;
  meses NUMBER;
  valido BOOLEAN;
BEGIN
  FOR e IN (SELECT ID_EMPLEADO,FECHA_INGRESO,FECHA_EGRESO FROM EMPLEADOS) LOOP
    corte := LEAST(TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE)),
                   NVL(e.FECHA_EGRESO,DATE '2199-12-31'));
    SELECT COUNT(*),MIN(VALOR) INTO cantidad,tasa FROM PARAMETROS_LEGALES
      WHERE CLAVE_INTERNA='VACACIONES_ACUMULACION_MENSUAL' AND UNIDAD='DIAS'
        AND ACTIVO=1 AND VIGENTE_DESDE<=corte AND (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA>=corte);
    IF cantidad=1 AND tasa>0 THEN
      SELECT MAX(FECHA) INTO apertura FROM VACACIONES_MOVIMIENTOS
        WHERE ID_EMPLEADO=e.ID_EMPLEADO AND TIPO='SALDO_INICIAL' AND ACTIVO=1 AND FECHA<=corte;
      anterior := 0; meses := 0; valido := TRUE;
      FOR n IN 1..GREATEST(0,12*(EXTRACT(YEAR FROM corte)-EXTRACT(YEAR FROM e.FECHA_INGRESO))
                              +EXTRACT(MONTH FROM corte)-EXTRACT(MONTH FROM e.FECHA_INGRESO)) LOOP
        aniversario := ADD_MONTHS(TRUNC(e.FECHA_INGRESO,'MM'),n)
          + LEAST(EXTRACT(DAY FROM e.FECHA_INGRESO),
                  EXTRACT(DAY FROM LAST_DAY(ADD_MONTHS(TRUNC(e.FECHA_INGRESO,'MM'),n)))) - 1;
        EXIT WHEN aniversario>corte;
        IF apertura IS NULL OR aniversario>apertura THEN
          meses := meses+1;
          SELECT COUNT(*),MIN(DIAS) INTO cantidad,valor_mes FROM VACACIONES_MOVIMIENTOS
            WHERE ID_EMPLEADO=e.ID_EMPLEADO AND ACTIVO=1 AND CLAVE_ORIGEN='MES:'||TO_CHAR(aniversario,'YYYY-MM-DD');
          IF cantidad=0 THEN
            SELECT COUNT(*),MIN(VALOR) INTO cantidad,valor_mes FROM PARAMETROS_LEGALES
              WHERE CLAVE_INTERNA='VACACIONES_ACUMULACION_MENSUAL' AND UNIDAD='DIAS'
                AND ACTIVO=1 AND VIGENTE_DESDE<=aniversario
                AND (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA>=aniversario);
          END IF;
          IF cantidad<>1 OR valor_mes<=0 THEN valido:=FALSE; EXIT; END IF;
          anterior := anterior+ROUND(valor_mes,2);
        END IF;
      END LOOP;
      nuevo := ROUND(meses*tasa,2);
      diferencia := anterior-nuevo;
      IF valido AND diferencia<>0 THEN
        INSERT INTO VACACIONES_MOVIMIENTOS(ID_EMPLEADO,TIPO,FECHA,DIAS,CLAVE_ORIGEN,MOTIVO)
          VALUES(e.ID_EMPLEADO,'AJUSTE',corte,diferencia,'MIGRACION_V1_8',
                 'Compensación al migrar acumulaciones v0 al cálculo determinista A9; snapshots y aprobaciones conservados');
      END IF;
    END IF;
  END LOOP;
END;
