-- Versiona las plantillas activas; los originales y los archivos emitidos permanecen íntegros.
BEGIN
  FOR P IN (SELECT * FROM PLANTILLAS_DOCUMENTO WHERE ACTIVO=1 AND VIGENTE_HASTA IS NULL) LOOP
    UPDATE PLANTILLAS_DOCUMENTO SET ACTIVO=0 WHERE ID_PLANTILLA_DOCUMENTO=P.ID_PLANTILLA_DOCUMENTO;
    INSERT INTO PLANTILLAS_DOCUMENTO (ID_TIPO_SOLICITUD,CODIGO,VERSION,NOMBRE,CONTENIDO,VARIABLES_PERMITIDAS,VIGENTE_DESDE)
    VALUES (P.ID_TIPO_SOLICITUD,P.CODIGO,P.VERSION+1,P.NOMBRE,
      REPLACE(P.CONTENIDO,'{{representante}}','{{firmante_nombre}}'),
      REPLACE(P.VARIABLES_PERMITIDAS,'"representante"','"firmante_nombre","firmante_cargo"'),P.VIGENTE_DESDE);
  END LOOP;
END;
/
-- Recupera la identidad verificable de aprobaciones históricas, sin inventar firmantes.
INSERT INTO FIRMAS_DOCUMENTO (ENTIDAD,ID_REGISTRO,ID_USUARIO,NOMBRE,CARGO,APROBADO_EN,CREADO_POR)
SELECT A.ENTIDAD,A.ID_REGISTRO,A.ID_USUARIO,TRIM(E.NOMBRES)||' '||TRIM(E.APELLIDOS),P.NOMBRE,A.FECHA,A.ID_USUARIO
FROM (
  SELECT 'PERIODOS_NOMINA' ENTIDAD,ID_PERIODO_NOMINA ID_REGISTRO,APROBADO_POR ID_USUARIO,APROBADO_EN FECHA FROM PERIODOS_NOMINA WHERE APROBADO_POR IS NOT NULL
  UNION ALL
  SELECT 'PRESTACIONES',ID_PRESTACION,APROBADO_POR,APROBADO_EN FROM PRESTACIONES WHERE APROBADO_POR IS NOT NULL
) A JOIN EMPLEADOS E ON E.ID_USUARIO=A.ID_USUARIO JOIN PUESTOS P ON P.ID_PUESTO=E.ID_PUESTO
WHERE TRIM(E.NOMBRES) IS NOT NULL AND TRIM(E.APELLIDOS) IS NOT NULL AND TRIM(P.NOMBRE) IS NOT NULL;
/
