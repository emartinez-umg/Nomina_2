ALTER TABLE SOLICITUD_HISTORIAL ADD CONSTRAINT CK_SOLICITUD_HISTORIAL_3 CHECK (
  (TIPO_MOVIMIENTO='ESTADO' AND (
    (ESTADO_ANTERIOR IS NULL AND ESTADO_NUEVO='EN_PROCESO') OR
    (ESTADO_ANTERIOR='EN_PROCESO' AND ESTADO_NUEVO IN ('APROBADA','RECHAZADA')) OR
    (ESTADO_ANTERIOR='APROBADA' AND ESTADO_NUEVO='ENTREGADA')
  )) OR
  (TIPO_MOVIMIENTO='REEMISION' AND ESTADO_ANTERIOR IN ('APROBADA','ENTREGADA') AND ESTADO_NUEVO='APROBADA' AND MOTIVO IS NOT NULL)
);
