-- Identidad ampliada; conserva la configuración y las referencias IGSS existentes.
CREATE TABLE IDENTIDAD_EMPRESA (
  ID_IDENTIDAD_EMPRESA NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_CONFIGURACION_EMPRESA NUMBER NOT NULL,
  NOMBRE_COMERCIAL VARCHAR2(200 CHAR),
  SITIO_WEB VARCHAR2(300 CHAR),
  LOGO_PNG BLOB,
  LOGO_SHA256 VARCHAR2(64 CHAR),
  VERSION NUMBER DEFAULT 1 NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_IDENTIDAD_EMPRESA PRIMARY KEY (ID_IDENTIDAD_EMPRESA),
  CONSTRAINT UQ_IDENTIDAD_EMPRESA UNIQUE (ID_CONFIGURACION_EMPRESA),
  CONSTRAINT FK_IDENTIDAD_EMPRESA FOREIGN KEY (ID_CONFIGURACION_EMPRESA) REFERENCES CONFIGURACION_EMPRESA (ID_CONFIGURACION_EMPRESA),
  CONSTRAINT CK_IDENTIDAD_EMPRESA_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_IDENTIDAD_EMPRESA_VERSION CHECK (VERSION>0),
  CONSTRAINT CK_IDENTIDAD_EMPRESA_LOGO CHECK (LOGO_SHA256 IS NULL OR LENGTH(LOGO_SHA256)=64)
);
/
INSERT INTO IDENTIDAD_EMPRESA (ID_CONFIGURACION_EMPRESA, CREADO_POR)
SELECT ID_CONFIGURACION_EMPRESA, CREADO_POR FROM CONFIGURACION_EMPRESA;
