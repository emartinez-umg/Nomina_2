-- FASE 1: prestaciones.

-- Liquidaciones de aguinaldo, Bono 14 e indemnización/finiquito.
CREATE TABLE PRESTACIONES (
  ID_PRESTACION NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_PERIODO_NOMINA NUMBER,
  TIPO VARCHAR2(15 CHAR) NOT NULL,
  FECHA_INICIO_BASE DATE NOT NULL,
  FECHA_FIN_BASE DATE NOT NULL,
  FECHA_CALCULO DATE NOT NULL,
  SALARIO_PROMEDIO NUMBER(12,2) NOT NULL,
  TIEMPO_ANIOS NUMBER(10,6) NOT NULL,
  MONTO_TOTAL NUMBER(12,2) NOT NULL,
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'CALCULADA' NOT NULL,
  FECHA_PAGO DATE,
  REFERENCIA_PAGO VARCHAR2(100 CHAR),
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PRESTACIONES PRIMARY KEY (ID_PRESTACION),
  CONSTRAINT CK_PRESTACIONES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_PRESTACIONES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_PRESTACIONES_1 CHECK (TIPO IN ('AGUINALDO','BONO_14','INDEMNIZACION')),
  CONSTRAINT CK_PRESTACIONES_2 CHECK (FECHA_FIN_BASE >= FECHA_INICIO_BASE),
  CONSTRAINT CK_PRESTACIONES_3 CHECK (SALARIO_PROMEDIO >= 0 AND TIEMPO_ANIOS >= 0 AND MONTO_TOTAL >= 0),
  CONSTRAINT CK_PRESTACIONES_4 CHECK (ESTADO IN ('CALCULADA','APROBADA','PAGADA','ANULADA')),
  CONSTRAINT CK_PRESTACIONES_5 CHECK (ESTADO <> 'PAGADA' OR (FECHA_PAGO IS NOT NULL AND REFERENCIA_PAGO IS NOT NULL)),
  CONSTRAINT UQ_PRESTACIONES_1 UNIQUE (ID_EMPLEADO, TIPO, FECHA_INICIO_BASE, FECHA_FIN_BASE),
  CONSTRAINT FK_PRESTACIONES_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_PRESTACIONES_2 FOREIGN KEY (ID_PERIODO_NOMINA) REFERENCES PERIODOS_NOMINA (ID_PERIODO_NOMINA)
);
/

CREATE INDEX IX_PRESTACIONES_1 ON PRESTACIONES (ID_PERIODO_NOMINA);
/

CREATE INDEX IX_PRESTACIONES_2 ON PRESTACIONES (TIPO);
/

CREATE INDEX IX_PRESTACIONES_3 ON PRESTACIONES (FECHA_CALCULO);
/

CREATE INDEX IX_PRESTACIONES_4 ON PRESTACIONES (ESTADO);
/

CREATE INDEX IX_PRESTACIONES_5 ON PRESTACIONES (FECHA_PAGO);
/

CREATE INDEX IX_PRESTACIONES_6 ON PRESTACIONES (ACTIVO);
/

CREATE INDEX IX_PRESTACIONES_7 ON PRESTACIONES (FECHA_CREACION);
/

-- Componentes de finiquito, exención, días y bases congeladas.
CREATE TABLE PRESTACION_DETALLE (
  ID_PRESTACION_DETALLE NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_PRESTACION NUMBER NOT NULL,
  CONCEPTO VARCHAR2(40 CHAR) NOT NULL,
  BASE_CALCULO NUMBER(12,2) NOT NULL,
  DIAS NUMBER(9,4) NOT NULL,
  MONTO NUMBER(12,2) NOT NULL,
  MONTO_EXENTO_ISR NUMBER(12,2) NOT NULL,
  DETALLE_CALCULO CLOB NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PRESTACION_DETALLE PRIMARY KEY (ID_PRESTACION_DETALLE),
  CONSTRAINT CK_PRESTACION_DETALLE_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_PRESTACION_DETALLE_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_PRESTACION_DETALLE_1 CHECK (BASE_CALCULO >= 0 AND DIAS >= 0 AND MONTO >= 0),
  CONSTRAINT CK_PRESTACION_DETALLE_2 CHECK (MONTO_EXENTO_ISR BETWEEN 0 AND MONTO),
  CONSTRAINT CK_PRESTACION_DETALLE_3 CHECK (DETALLE_CALCULO IS JSON),
  CONSTRAINT UQ_PRESTACION_DETALLE_1 UNIQUE (ID_PRESTACION, CONCEPTO),
  CONSTRAINT FK_PRESTACION_DETALLE_1 FOREIGN KEY (ID_PRESTACION) REFERENCES PRESTACIONES (ID_PRESTACION)
);
/

CREATE INDEX IX_PRESTACION_DETALLE_1 ON PRESTACION_DETALLE (CONCEPTO);
/

CREATE INDEX IX_PRESTACION_DETALLE_2 ON PRESTACION_DETALLE (ACTIVO);
/

CREATE INDEX IX_PRESTACION_DETALLE_3 ON PRESTACION_DETALLE (FECHA_CREACION);
/
