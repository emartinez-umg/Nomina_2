-- Prerrequisito de V031: un UNIQUE exacto anterior no debe impedir recortar al más antiguo.
-- Sobre V031 ya aplicada solo retira restricciones redundantes; permanece el UNIQUE normalizado.
DECLARE
  V_INDICES NUMBER;
BEGIN
  FOR R IN (SELECT TABLE_NAME,CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE CONSTRAINT_TYPE='U'
            AND CONSTRAINT_NAME IN ('UQ_PARENTESCOS_NOMBRE','UQ_DEPARTAMENTOS_GT_NOMBRE','UQ_MUNICIPIOS_GT_DEP_NOM')) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE '||R.TABLE_NAME||' DROP CONSTRAINT '||R.CONSTRAINT_NAME;
  END LOOP;
  FOR T IN (SELECT COLUMN_VALUE TABLA FROM TABLE(SYS.ODCIVARCHAR2LIST('PARENTESCOS','DEPARTAMENTOS_GT','MUNICIPIOS_GT'))) LOOP
    SELECT COUNT(*) INTO V_INDICES FROM USER_IND_COLUMNS
      WHERE TABLE_NAME=T.TABLA AND COLUMN_NAME='NOMBRE' AND COLUMN_POSITION=1;
    IF V_INDICES=0 THEN
      EXECUTE IMMEDIATE 'CREATE INDEX IX_'||T.TABLA||'_NOMBRE ON '||T.TABLA||'(NOMBRE)';
    END IF;
  END LOOP;
  -- El UNIQUE (departamento,nombre) anterior también cubría la FK del municipio.
  SELECT COUNT(*) INTO V_INDICES FROM USER_IND_COLUMNS
    WHERE TABLE_NAME='MUNICIPIOS_GT' AND COLUMN_NAME='ID_DEPARTAMENTO_GT' AND COLUMN_POSITION=1;
  IF V_INDICES=0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_MUNICIPIOS_GT_DEP_R2 ON MUNICIPIOS_GT(ID_DEPARTAMENTO_GT)';
  END IF;
END;
/
