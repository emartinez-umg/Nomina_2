-- R2-4: normalización independiente de NLS y conservación de correcciones históricas.
CREATE OR REPLACE FUNCTION N2_NOMBRE_NORMALIZADO(P_NOMBRE VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
BEGIN
  RETURN LOWER(REGEXP_REPLACE(DECOMPOSE(TRIM(REGEXP_REPLACE(P_NOMBRE,'[[:space:]]+',' '))),UNISTR('[\0300-\036F]'),''));
END;
/
CREATE TABLE CATALOGOS_NOMBRES_CORREGIDOS (
  ID_CATALOGO_NOMBRE_CORREGIDO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
  TABLA VARCHAR2(60 CHAR) NOT NULL,
  ID_REGISTRO NUMBER NOT NULL,
  NOMBRE_ANTERIOR VARCHAR2(200 CHAR) NOT NULL,
  NOMBRE_NUEVO VARCHAR2(200 CHAR) NOT NULL,
  FECHA DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL
);
/
DECLARE
  TYPE CURSOR_NOMBRES IS REF CURSOR;
  C CURSOR_NOMBRES;
  V_ID NUMBER;
  V_NOMBRE VARCHAR2(200 CHAR);
  V_LIMPIO VARCHAR2(200 CHAR);
  V_NUEVO VARCHAR2(200 CHAR);
  V_GRUPO VARCHAR2(100 CHAR);
  V_CUENTA NUMBER;
  V_NUMERO NUMBER;
  V_MAX NUMBER;
  V_SQL VARCHAR2(32767);
  V_INDICE VARCHAR2(200 CHAR);
BEGIN
  FOR T IN (
    SELECT TABLE_NAME TABLA, COLUMN_NAME PK FROM USER_TAB_IDENTITY_COLS
    WHERE TABLE_NAME IN ('BANCOS','CENTROS_TRABAJO','DEPARTAMENTOS','PUESTOS','JEFATURAS','HORARIOS','FERIADOS','TIPOS_AUSENCIA','TIPOS_DESCUENTO','TIPOS_CONTRATO','PARENTESCOS','TIPOS_SOLICITUD','TIPOS_DEDUCCION_ISR','CONCEPTOS_NOMINA','PARAMETROS_LEGALES','ROLES','DEPARTAMENTOS_GT','MUNICIPIOS_GT')
    ORDER BY TABLE_NAME
  ) LOOP
    SELECT CHAR_LENGTH INTO V_MAX FROM USER_TAB_COLUMNS WHERE TABLE_NAME=T.TABLA AND COLUMN_NAME='NOMBRE';
    EXECUTE IMMEDIATE 'ALTER TABLE '||T.TABLA||' ADD NOMBRE_NORMALIZADO VARCHAR2('||V_MAX||' CHAR)';
    -- Vigencias representan versiones de una identidad; municipios oficiales se distinguen por departamento.
    V_SQL := 'SELECT '||T.PK||',NOMBRE,'||CASE WHEN T.TABLA IN ('PARAMETROS_LEGALES','CONCEPTOS_NOMINA') THEN 'TO_CHAR(VIGENTE_DESDE,''YYYY-MM-DD'')' WHEN T.TABLA='MUNICIPIOS_GT' THEN 'TO_CHAR(ID_DEPARTAMENTO_GT)' ELSE 'NULL' END||' FROM '||T.TABLA||' ORDER BY FECHA_CREACION,'||T.PK;
    OPEN C FOR V_SQL;
    LOOP
      FETCH C INTO V_ID,V_NOMBRE,V_GRUPO;
      EXIT WHEN C%NOTFOUND;
      V_LIMPIO := TRIM(REGEXP_REPLACE(V_NOMBRE,'[[:space:]]+',' '));
      V_NUEVO := V_LIMPIO;
      V_NUMERO := 1;
      LOOP
        V_SQL := 'SELECT COUNT(*) FROM '||T.TABLA||' WHERE NOMBRE_NORMALIZADO=N2_NOMBRE_NORMALIZADO(:nombre)';
        IF T.TABLA IN ('PARAMETROS_LEGALES','CONCEPTOS_NOMINA') THEN
          EXECUTE IMMEDIATE V_SQL||' AND VIGENTE_DESDE=TO_DATE(:grupo,''YYYY-MM-DD'')' INTO V_CUENTA USING V_NUEVO,V_GRUPO;
        ELSIF T.TABLA='MUNICIPIOS_GT' THEN
          EXECUTE IMMEDIATE V_SQL||' AND ID_DEPARTAMENTO_GT=TO_NUMBER(:grupo)' INTO V_CUENTA USING V_NUEVO,V_GRUPO;
        ELSE
          EXECUTE IMMEDIATE V_SQL INTO V_CUENTA USING V_NUEVO;
        END IF;
        EXIT WHEN V_CUENTA=0;
        V_NUMERO := V_NUMERO+1;
        V_NUEVO := SUBSTR(V_LIMPIO,1,V_MAX-LENGTH(' (duplicado '||V_NUMERO||')'))||' (duplicado '||V_NUMERO||')';
        -- Evita colisionar también con un nombre todavía no procesado.
        V_SQL := 'SELECT COUNT(*) FROM '||T.TABLA||' WHERE N2_NOMBRE_NORMALIZADO(NOMBRE)=N2_NOMBRE_NORMALIZADO(:nombre) AND '||T.PK||'<>:id';
        EXECUTE IMMEDIATE V_SQL INTO V_CUENTA USING V_NUEVO,V_ID;
        WHILE V_CUENTA>0 LOOP
          V_NUMERO := V_NUMERO+1;
          V_NUEVO := SUBSTR(V_LIMPIO,1,V_MAX-LENGTH(' (duplicado '||V_NUMERO||')'))||' (duplicado '||V_NUMERO||')';
          EXECUTE IMMEDIATE V_SQL INTO V_CUENTA USING V_NUEVO,V_ID;
        END LOOP;
      END LOOP;
      IF V_NUMERO>1 THEN
        INSERT INTO CATALOGOS_NOMBRES_CORREGIDOS(TABLA,ID_REGISTRO,NOMBRE_ANTERIOR,NOMBRE_NUEVO) VALUES(T.TABLA,V_ID,V_NOMBRE,V_NUEVO);
      END IF;
      EXECUTE IMMEDIATE 'UPDATE '||T.TABLA||' SET NOMBRE=:nombre,NOMBRE_NORMALIZADO=N2_NOMBRE_NORMALIZADO(:normalizado),ACTIVO=CASE WHEN :duplicado>1 THEN 0 ELSE ACTIVO END WHERE '||T.PK||'=:id' USING V_NUEVO,V_NUEVO,V_NUMERO,V_ID;
    END LOOP;
    CLOSE C;
    EXECUTE IMMEDIATE 'ALTER TABLE '||T.TABLA||' MODIFY NOMBRE_NORMALIZADO NOT NULL';
    V_INDICE := CASE WHEN T.TABLA IN ('PARAMETROS_LEGALES','CONCEPTOS_NOMINA') THEN ',VIGENTE_DESDE' WHEN T.TABLA='MUNICIPIOS_GT' THEN ',ID_DEPARTAMENTO_GT' ELSE '' END;
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_'||T.TABLA||'_NOMBRE_NORM ON '||T.TABLA||'(NOMBRE_NORMALIZADO'||V_INDICE||')';
    EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER TR_'||T.TABLA||'_NOMBRE_NORM BEFORE INSERT OR UPDATE OF NOMBRE,NOMBRE_NORMALIZADO ON '||T.TABLA||' FOR EACH ROW BEGIN :NEW.NOMBRE:=TRIM(REGEXP_REPLACE(:NEW.NOMBRE,''[[:space:]]+'','' '')); :NEW.NOMBRE_NORMALIZADO:=N2_NOMBRE_NORMALIZADO(:NEW.NOMBRE); END;';
  END LOOP;
END;
