CREATE OR REPLACE TRIGGER TR_CONCEPTOS_CODIGO BEFORE INSERT OR UPDATE OF CODIGO ON CONCEPTOS_NOMINA FOR EACH ROW
BEGIN
  IF INSERTING AND :NEW.CODIGO IS NULL THEN
    :NEW.CODIGO:=N2_CODIGOS.ASIGNAR('conceptos',:NEW.NOMBRE,NULL,:NEW.FECHA_CREACION,NULL);
  ELSIF UPDATING AND (:NEW.CODIGO<>:OLD.CODIGO OR :NEW.CODIGO IS NULL) THEN
    RAISE_APPLICATION_ERROR(-20042,'El código es permanente.');
  END IF;
END;
/
CREATE OR REPLACE TRIGGER TR_TIPO_DED_ISR_CODIGO BEFORE INSERT OR UPDATE OF CODIGO ON TIPOS_DEDUCCION_ISR FOR EACH ROW
BEGIN
  IF INSERTING AND :NEW.CODIGO IS NULL THEN
    :NEW.CODIGO:=N2_CODIGOS.ASIGNAR('tipos-deduccion-isr',:NEW.NOMBRE,NULL,:NEW.FECHA_CREACION,NULL);
  ELSIF UPDATING AND (:NEW.CODIGO<>:OLD.CODIGO OR :NEW.CODIGO IS NULL) THEN
    RAISE_APPLICATION_ERROR(-20042,'El código es permanente.');
  END IF;
END;
