CREATE TABLE TIPOS_ACTA (
 ID_TIPO_ACTA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 CODIGO VARCHAR2(80 CHAR) NOT NULL UNIQUE,
 CODIGO_ANTERIOR VARCHAR2(80 CHAR),
 NOMBRE VARCHAR2(120 CHAR) NOT NULL,
 NOMBRE_NORMALIZADO VARCHAR2(240 CHAR) NOT NULL UNIQUE,
 DESCRIPCION VARCHAR2(500 CHAR),
 GRAVEDAD VARCHAR2(10) NOT NULL CHECK (GRAVEDAD IN ('LEVE','MODERADA','GRAVE')),
 ES_SUSPENSION NUMBER(1) DEFAULT 0 NOT NULL CHECK (ES_SUSPENSION IN (0,1)),
 ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0,1)),
 CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
 MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 FECHA_MODIFICACION DATE
);
/
