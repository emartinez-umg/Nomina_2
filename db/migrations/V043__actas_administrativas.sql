CREATE OR REPLACE TRIGGER TR_TIPO_ACTA_NOMBRE BEFORE INSERT OR UPDATE OF NOMBRE ON TIPOS_ACTA FOR EACH ROW
BEGIN
 :NEW.NOMBRE_NORMALIZADO:=N2_NOMBRE_NORMALIZADO(:NEW.NOMBRE);
END;
