CREATE TABLE ACTAS_ADMINISTRATIVAS (
 ID_ACTA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 CODIGO VARCHAR2(80 CHAR) NOT NULL UNIQUE,
 ID_EMPLEADO NUMBER NOT NULL REFERENCES EMPLEADOS(ID_EMPLEADO),
 ID_TIPO_ACTA NUMBER NOT NULL REFERENCES TIPOS_ACTA(ID_TIPO_ACTA),
 FECHA_HECHO DATE NOT NULL,
 LUGAR VARCHAR2(200 CHAR) NOT NULL,
 DESCRIPCION CLOB NOT NULL,
 TESTIGOS VARCHAR2(1000 CHAR),
 NORMA VARCHAR2(1000 CHAR) NOT NULL,
 MEDIDA VARCHAR2(1000 CHAR) NOT NULL,
 DESCARGOS VARCHAR2(1000 CHAR),
 DIAS_SUSPENSION NUMBER(3) DEFAULT 0 NOT NULL CHECK (DIAS_SUSPENSION BETWEEN 0 AND 366),
 ESTADO VARCHAR2(20) DEFAULT 'BORRADOR' NOT NULL CHECK (ESTADO IN ('BORRADOR','EMITIDA','FIRMADA','SE_NEGO_A_FIRMAR','ANULADA')),
 VERSION NUMBER DEFAULT 1 NOT NULL CHECK (VERSION>0),
 EMITIDA_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 EMITIDA_EN DATE,
 EMISOR_NOMBRE VARCHAR2(250 CHAR),
 EMISOR_CARGO VARCHAR2(120 CHAR),
 ID_PLANTILLA_DOCUMENTO NUMBER REFERENCES PLANTILLAS_DOCUMENTO(ID_PLANTILLA_DOCUMENTO),
 CONTENIDO_PDF BLOB,
 PDF_SHA256 VARCHAR2(64),
 ID_AUSENCIA NUMBER UNIQUE REFERENCES AUSENCIAS(ID_AUSENCIA),
 ANULADA_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 ANULADA_EN DATE,
 MOTIVO_ANULACION VARCHAR2(500 CHAR),
 ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO=1),
 CREADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
 MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 FECHA_MODIFICACION DATE,
 CONSTRAINT CK_ACTA_EMISION CHECK (ESTADO IN ('BORRADOR','ANULADA') OR (EMITIDA_POR IS NOT NULL AND EMITIDA_EN IS NOT NULL AND EMISOR_NOMBRE IS NOT NULL AND EMISOR_CARGO IS NOT NULL AND CONTENIDO_PDF IS NOT NULL AND PDF_SHA256 IS NOT NULL)),
 CONSTRAINT CK_ACTA_ANULACION CHECK (ESTADO<>'ANULADA' OR (ANULADA_POR IS NOT NULL AND ANULADA_EN IS NOT NULL AND MOTIVO_ANULACION IS NOT NULL))
);
/
CREATE OR REPLACE TRIGGER TR_ACTA_COD BEFORE INSERT OR UPDATE OF CODIGO ON ACTAS_ADMINISTRATIVAS FOR EACH ROW
BEGIN
 IF INSERTING THEN :NEW.CODIGO:=N2_CODIGOS.ASIGNAR('actas',NULL,NULL,:NEW.FECHA_CREACION);
 ELSIF :NEW.CODIGO<>:OLD.CODIGO THEN RAISE_APPLICATION_ERROR(-20042,'Código permanente'); END IF;
END;
/
CREATE TABLE ACTA_HISTORIAL (
 ID_ACTA_HISTORIAL NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ID_ACTA NUMBER NOT NULL REFERENCES ACTAS_ADMINISTRATIVAS(ID_ACTA),
 ESTADO_ANTERIOR VARCHAR2(20),
 ESTADO_NUEVO VARCHAR2(20) NOT NULL CHECK (ESTADO_NUEVO IN ('BORRADOR','EMITIDA','FIRMADA','SE_NEGO_A_FIRMAR','ANULADA')),
 MOTIVO VARCHAR2(500 CHAR),
 TESTIGOS VARCHAR2(1000 CHAR),
 ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO=1),
 CREADO_POR NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
 FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
 MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 FECHA_MODIFICACION DATE
);
/
CREATE TABLE ACTA_ADJUNTOS (
 ID_ACTA_ADJUNTO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ID_ACTA NUMBER NOT NULL REFERENCES ACTAS_ADMINISTRATIVAS(ID_ACTA),
 CLASE VARCHAR2(10) NOT NULL CHECK (CLASE IN ('EVIDENCIA','FIRMA')),
 NOMBRE_ARCHIVO VARCHAR2(200 CHAR) NOT NULL,
 CLAVE_ARCHIVO VARCHAR2(68) NOT NULL UNIQUE CHECK (REGEXP_LIKE(CLAVE_ARCHIVO,'^[a-f0-9]{64}\.bin$')),
 TIPO_CONTENIDO VARCHAR2(20) NOT NULL CHECK (TIPO_CONTENIDO IN ('application/pdf','image/jpeg','image/png')),
 TAMANO_BYTES NUMBER(10) NOT NULL CHECK (TAMANO_BYTES>0),
 HASH_SHA256 VARCHAR2(64) NOT NULL,
 ACTIVO NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVO=1),
 CREADO_POR NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
 FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
 MODIFICADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
 FECHA_MODIFICACION DATE
);
/
