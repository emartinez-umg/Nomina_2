-- FASE 1: vacaciones.

-- Rango y días laborales al solicitar y resolver; vínculo con solicitud en V010.
CREATE TABLE VACACIONES_SOLICITUDES (
  ID_VACACIONES_SOLICITUD NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  FECHA_INICIO DATE NOT NULL,
  FECHA_FIN DATE NOT NULL,
  DIAS_SOLICITADOS NUMBER(7,2) NOT NULL,
  SALDO_AL_SOLICITAR NUMBER(7,2) NOT NULL,
  SALDO_AL_RESOLVER NUMBER(7,2),
  ESTADO VARCHAR2(12 CHAR) DEFAULT 'EN_PROCESO' NOT NULL,
  RESUELTO_POR NUMBER,
  RESUELTO_EN DATE,
  MOTIVO_RECHAZO VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_VACACIONES_SOLICITUDES PRIMARY KEY (ID_VACACIONES_SOLICITUD),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_1 CHECK (FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_2 CHECK (DIAS_SOLICITADOS > 0),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_3 CHECK (SALDO_AL_SOLICITAR >= 0),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_4 CHECK (SALDO_AL_RESOLVER >= 0),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_5 CHECK (ESTADO IN ('EN_PROCESO','APROBADA','RECHAZADA','CANCELADA','TOMADA')),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_6 CHECK (ESTADO NOT IN ('APROBADA','TOMADA') OR (SALDO_AL_RESOLVER IS NOT NULL AND SALDO_AL_RESOLVER >= DIAS_SOLICITADOS AND RESUELTO_POR IS NOT NULL AND RESUELTO_EN IS NOT NULL)),
  CONSTRAINT CK_VACACIONES_SOLICITUDES_7 CHECK (ESTADO <> 'RECHAZADA' OR (MOTIVO_RECHAZO IS NOT NULL AND RESUELTO_POR IS NOT NULL AND RESUELTO_EN IS NOT NULL)),
  CONSTRAINT UQ_VACACIONES_SOLICITUDES_1 UNIQUE (ID_VACACIONES_SOLICITUD, ID_EMPLEADO),
  CONSTRAINT FK_VACACIONES_SOLICITUDES_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_VACACIONES_SOLICITUDES_2 FOREIGN KEY (RESUELTO_POR) REFERENCES USUARIOS (ID_USUARIO)
);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_1 ON VACACIONES_SOLICITUDES (ID_EMPLEADO);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_2 ON VACACIONES_SOLICITUDES (RESUELTO_POR);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_3 ON VACACIONES_SOLICITUDES (FECHA_INICIO);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_4 ON VACACIONES_SOLICITUDES (FECHA_FIN);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_5 ON VACACIONES_SOLICITUDES (ESTADO);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_6 ON VACACIONES_SOLICITUDES (ACTIVO);
/

CREATE INDEX IX_VACACIONES_SOLICITUDES_7 ON VACACIONES_SOLICITUDES (FECHA_CREACION);
/

-- Kardex con débito/reserva al aprobar; reversión explícita y ajustes motivados.
CREATE TABLE VACACIONES_MOVIMIENTOS (
  ID_VACACIONES_MOVIMIENTO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_VACACIONES_SOLICITUD NUMBER,
  TIPO VARCHAR2(15 CHAR) NOT NULL,
  FECHA DATE NOT NULL,
  DIAS NUMBER(7,2) NOT NULL,
  CLAVE_ORIGEN VARCHAR2(100 CHAR) NOT NULL,
  MOTIVO VARCHAR2(500 CHAR) NOT NULL,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_VACACIONES_MOVIMIENTOS PRIMARY KEY (ID_VACACIONES_MOVIMIENTO),
  CONSTRAINT CK_VACACIONES_MOVIMIENTOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_VACACIONES_MOVIMIENTOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_VACACIONES_MOVIMIENTOS_1 CHECK (TIPO IN ('ACUMULACION','DISFRUTE','REVERSO','AJUSTE')),
  CONSTRAINT CK_VACACIONES_MOVIMIENTOS_2 CHECK (DIAS <> 0),
  CONSTRAINT CK_VACACIONES_MOVIMIENTOS_3 CHECK ((TIPO IN ('ACUMULACION','REVERSO') AND DIAS > 0) OR (TIPO = 'DISFRUTE' AND DIAS < 0) OR TIPO = 'AJUSTE'),
  CONSTRAINT CK_VACACIONES_MOVIMIENTOS_4 CHECK (TIPO NOT IN ('DISFRUTE','REVERSO') OR ID_VACACIONES_SOLICITUD IS NOT NULL),
  CONSTRAINT UQ_VACACIONES_MOVIMIENTOS_1 UNIQUE (ID_EMPLEADO, CLAVE_ORIGEN),
  CONSTRAINT FK_VACACIONES_MOVIMIENTOS_1 FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_VACACIONES_MOVIMIENTOS_2 FOREIGN KEY (ID_VACACIONES_SOLICITUD, ID_EMPLEADO) REFERENCES VACACIONES_SOLICITUDES (ID_VACACIONES_SOLICITUD, ID_EMPLEADO)
);
/

CREATE INDEX IX_VACACIONES_MOVIMIENTOS_1 ON VACACIONES_MOVIMIENTOS (ID_VACACIONES_SOLICITUD, ID_EMPLEADO);
/

CREATE INDEX IX_VACACIONES_MOVIMIENTOS_2 ON VACACIONES_MOVIMIENTOS (TIPO);
/

CREATE INDEX IX_VACACIONES_MOVIMIENTOS_3 ON VACACIONES_MOVIMIENTOS (FECHA);
/

CREATE INDEX IX_VACACIONES_MOVIMIENTOS_4 ON VACACIONES_MOVIMIENTOS (ACTIVO);
/

CREATE INDEX IX_VACACIONES_MOVIMIENTOS_5 ON VACACIONES_MOVIMIENTOS (FECHA_CREACION);
/
