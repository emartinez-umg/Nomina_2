DECLARE V_ID NUMBER;
BEGIN
 FOR P IN (SELECT S.ID_PARQUEO_SUSCRIPCION,S.ID_EMPLEADO,TRUNC(P.FECHA_INICIO,'MM') MES,SUM(A.MONTO) MONTO,MAX(A.ID_NOMINA_EMPLEADO) PAGO FROM PARQUEO_SUSCRIPCIONES S JOIN DESCUENTOS_APLICACIONES A ON A.ID_DESCUENTO_EMPLEADO=S.ID_DESCUENTO_ORIGEN JOIN PERIODOS_NOMINA P ON P.ID_PERIODO_NOMINA=A.ID_PERIODO_NOMINA GROUP BY S.ID_PARQUEO_SUSCRIPCION,S.ID_EMPLEADO,TRUNC(P.FECHA_INICIO,'MM')) LOOP
  INSERT INTO NOVEDADES_MENSUALES(ID_EMPLEADO,TIPO,MES,MONTO,DESCRIPCION,ESTADO,ID_NOMINA_EMPLEADO,ID_PARQUEO_SUSCRIPCION) VALUES(P.ID_EMPLEADO,'PARQUEO',P.MES,P.MONTO,'Parqueo v0 aplicado; importes y pagos originales conservados','APLICADA',P.PAGO,P.ID_PARQUEO_SUSCRIPCION) RETURNING ID_NOVEDAD_MENSUAL INTO V_ID;
  INSERT INTO NOVEDADES_ORIGEN(ID_NOVEDAD_MENSUAL,ENTIDAD,ID_ORIGEN) SELECT V_ID,'DESCUENTOS_APLICACIONES',A.ID_DESCUENTO_APLICACION FROM DESCUENTOS_APLICACIONES A JOIN PARQUEO_SUSCRIPCIONES S ON S.ID_DESCUENTO_ORIGEN=A.ID_DESCUENTO_EMPLEADO JOIN PERIODOS_NOMINA Q ON Q.ID_PERIODO_NOMINA=A.ID_PERIODO_NOMINA WHERE S.ID_PARQUEO_SUSCRIPCION=P.ID_PARQUEO_SUSCRIPCION AND TRUNC(Q.FECHA_INICIO,'MM')=P.MES;
 END LOOP;
