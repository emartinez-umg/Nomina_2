-- Las ausencias conservan los snapshots consumidos; solo días aún no consumidos quedan pendientes.
DECLARE
 V_MES DATE; V_DIA DATE; V_FIN DATE; V_DIAS NUMBER; V_MONTO NUMBER; V_SALARIO NUMBER; V_USADO NUMBER;
BEGIN
 FOR A IN (SELECT A.*,T.EFECTO FROM AUSENCIAS A JOIN TIPOS_AUSENCIA T ON T.ID_TIPO_AUSENCIA=A.ID_TIPO_AUSENCIA) LOOP
  FOR P IN (SELECT TRUNC(P.FECHA_INICIO,'MM') MES,N.ID_NOMINA_EMPLEADO,SUM(N.CANTIDAD) DIAS,SUM(N.MONTO) MONTO FROM NOMINA_DETALLE N JOIN PERIODOS_NOMINA P ON P.ID_PERIODO_NOMINA=N.ID_PERIODO_NOMINA WHERE N.ID_AUSENCIA=A.ID_AUSENCIA GROUP BY TRUNC(P.FECHA_INICIO,'MM'),N.ID_NOMINA_EMPLEADO) LOOP
   INSERT INTO NOVEDADES_MENSUALES(ID_EMPLEADO,TIPO,MES,CANTIDAD,MONTO,DESCRIPCION,AUTORIZACION,ESTADO,ID_NOMINA_EMPLEADO,ID_AUSENCIA,ACTIVO) VALUES(A.ID_EMPLEADO,'AUSENCIA',P.MES,GREATEST(P.DIAS,1),P.MONTO,'Descuento por ausencias migrado; boleta original conservada',A.ESTADO,'APLICADA',P.ID_NOMINA_EMPLEADO,A.ID_AUSENCIA,A.ACTIVO);
  END LOOP;
  V_MES:=TRUNC(A.FECHA_INICIO,'MM');
  WHILE V_MES<=A.FECHA_FIN LOOP
   V_DIA:=GREATEST(V_MES,A.FECHA_INICIO); V_FIN:=LEAST(LAST_DAY(V_MES),A.FECHA_FIN);V_DIAS:=0;V_MONTO:=0;
   WHILE V_DIA<=V_FIN LOOP
    SELECT COUNT(*) INTO V_USADO FROM NOMINA_DETALLE N JOIN PERIODOS_NOMINA P ON P.ID_PERIODO_NOMINA=N.ID_PERIODO_NOMINA WHERE N.ID_AUSENCIA=A.ID_AUSENCIA AND V_DIA BETWEEN P.FECHA_INICIO AND P.FECHA_FIN;
    IF V_USADO=0 THEN
     V_DIAS:=V_DIAS+1;
     IF A.EFECTO='SIN_GOCE' THEN
      SELECT MAX(SALARIO_BASE) INTO V_SALARIO FROM HISTORIAL_SALARIAL WHERE ID_EMPLEADO=A.ID_EMPLEADO AND ACTIVO=1 AND VIGENTE_DESDE<=V_DIA AND (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA>=V_DIA);
      IF V_SALARIO IS NULL THEN V_MONTO:=NULL; ELSE V_MONTO:=V_MONTO+V_SALARIO/30; END IF;
     END IF;
    END IF;
    V_DIA:=V_DIA+1;
   END LOOP;
   IF V_DIAS>0 THEN
    INSERT INTO NOVEDADES_MENSUALES(ID_EMPLEADO,TIPO,MES,CANTIDAD,MONTO,DESCRIPCION,AUTORIZACION,ID_AUSENCIA,ACTIVO) VALUES(A.ID_EMPLEADO,'AUSENCIA',V_MES,V_DIAS,ROUND(V_MONTO,2),'Descuento por ausencias, '||V_DIAS||' días',A.ESTADO,A.ID_AUSENCIA,A.ACTIVO);
   END IF;
   V_MES:=ADD_MONTHS(V_MES,1);
  END LOOP;
 END LOOP;
END;
/

