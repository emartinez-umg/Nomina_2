-- FASE 1: seguridad.

-- Roles de acceso: ADMIN, RH y EMPLEADO.
CREATE TABLE ROLES (
  ID_ROL NUMBER GENERATED ALWAYS AS IDENTITY,
  CODIGO VARCHAR2(40 CHAR) NOT NULL,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  DESCRIPCION VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
  CONSTRAINT CK_ROLES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_ROLES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_ROLES_1 CHECK (CODIGO IN ('ADMIN','RH','EMPLEADO')),
  CONSTRAINT UQ_ROLES_1 UNIQUE (CODIGO)
);
/

CREATE INDEX IX_ROLES_1 ON ROLES (NOMBRE);
/

CREATE INDEX IX_ROLES_2 ON ROLES (ACTIVO);
/

CREATE INDEX IX_ROLES_3 ON ROLES (FECHA_CREACION);
/

-- Identidad, credencial argon2id, bloqueo y cambio inicial obligatorio.
CREATE TABLE USUARIOS (
  ID_USUARIO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_ROL NUMBER NOT NULL,
  USUARIO VARCHAR2(80 CHAR) NOT NULL,
  CORREO VARCHAR2(254 CHAR) NOT NULL,
  CONTRASENA_HASH VARCHAR2(255 CHAR) NOT NULL,
  CAMBIO_OBLIGATORIO NUMBER(1) DEFAULT 1 NOT NULL,
  INTENTOS_FALLIDOS NUMBER(2) DEFAULT 0 NOT NULL,
  BLOQUEADO_HASTA DATE,
  ULTIMO_ACCESO DATE,
  CONTRASENA_CAMBIADA_EN DATE,
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
  CONSTRAINT CK_USUARIOS_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_USUARIOS_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_USUARIOS_1 CHECK (REGEXP_LIKE(USUARIO, '^[a-z][a-z0-9.]{2,79}$', 'c')),
  CONSTRAINT CK_USUARIOS_2 CHECK (CORREO = LOWER(TRIM(CORREO)) AND INSTR(CORREO, '@') > 1),
  CONSTRAINT CK_USUARIOS_3 CHECK (CONTRASENA_HASH LIKE '$argon2id$%'),
  CONSTRAINT CK_USUARIOS_4 CHECK (CAMBIO_OBLIGATORIO IN (0,1)),
  CONSTRAINT CK_USUARIOS_5 CHECK (INTENTOS_FALLIDOS BETWEEN 0 AND 99),
  CONSTRAINT UQ_USUARIOS_1 UNIQUE (USUARIO),
  CONSTRAINT UQ_USUARIOS_2 UNIQUE (CORREO),
  CONSTRAINT FK_USUARIOS_1 FOREIGN KEY (ID_ROL) REFERENCES ROLES (ID_ROL)
);
/

CREATE INDEX IX_USUARIOS_1 ON USUARIOS (ID_ROL);
/

CREATE INDEX IX_USUARIOS_2 ON USUARIOS (BLOQUEADO_HASTA);
/

CREATE INDEX IX_USUARIOS_3 ON USUARIOS (ULTIMO_ACCESO);
/

CREATE INDEX IX_USUARIOS_4 ON USUARIOS (CAMBIO_OBLIGATORIO);
/

CREATE INDEX IX_USUARIOS_5 ON USUARIOS (ACTIVO);
/

CREATE INDEX IX_USUARIOS_6 ON USUARIOS (FECHA_CREACION);
/

-- Solo hashes SHA-256 de sesión y CSRF; actividad y revocación.
CREATE TABLE SESIONES (
  ID_SESION NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_USUARIO NUMBER NOT NULL,
  TOKEN_HASH RAW(32) NOT NULL,
  CSRF_HASH RAW(32) NOT NULL,
  ULTIMA_ACTIVIDAD DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  EXPIRA_EN DATE NOT NULL,
  REVOCADA_EN DATE,
  IP VARCHAR2(45 CHAR),
  AGENTE_USUARIO VARCHAR2(500 CHAR),
  CREADO_POR NUMBER,
  FECHA_CREACION DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Guatemala' AS DATE) NOT NULL,
  MODIFICADO_POR NUMBER,
  FECHA_MODIFICACION DATE,
  ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_SESIONES PRIMARY KEY (ID_SESION),
  CONSTRAINT CK_SESIONES_ACT CHECK (ACTIVO IN (0,1)),
  CONSTRAINT CK_SESIONES_MOD CHECK (FECHA_MODIFICACION IS NULL OR FECHA_MODIFICACION >= FECHA_CREACION),
  CONSTRAINT CK_SESIONES_1 CHECK (EXPIRA_EN > ULTIMA_ACTIVIDAD),
  CONSTRAINT CK_SESIONES_2 CHECK (REVOCADA_EN IS NULL OR REVOCADA_EN >= FECHA_CREACION),
  CONSTRAINT UQ_SESIONES_1 UNIQUE (TOKEN_HASH),
  CONSTRAINT FK_SESIONES_1 FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);
/

CREATE INDEX IX_SESIONES_1 ON SESIONES (ID_USUARIO);
/

CREATE INDEX IX_SESIONES_2 ON SESIONES (ULTIMA_ACTIVIDAD);
/

CREATE INDEX IX_SESIONES_3 ON SESIONES (EXPIRA_EN);
/

CREATE INDEX IX_SESIONES_4 ON SESIONES (REVOCADA_EN);
/

CREATE INDEX IX_SESIONES_5 ON SESIONES (ACTIVO);
/

CREATE INDEX IX_SESIONES_6 ON SESIONES (FECHA_CREACION);
/
